#!/usr/bin/env python3
"""research transparent unary-count CNF for dim-2 occupation certificates.

This script is intentionally more proof-readable than the PySAT seqcounter files
from research.  It encodes the same integer occupation core using count variables

    u[p,ell]  <=>  x_p >= ell,   p=1..2^k-1, ell=1..L,

but every auxiliary counter is generated by a small explicit prefix-count scheme.
The property used by the mathematical proof is the forward lifting property: if
nonnegative integer counts x_p of total L satisfy the selected occupation rows,
then setting u[p,ell]=(ell<=x_p) and setting every prefix-counter variable to the
corresponding prefix-threshold truth value satisfies every emitted clause.
Therefore a DRAT proof of UNSAT for the emitted CNF proves that no legal integer
occupation vector exists.  The CNF may also enforce more than the forward
property; the proof transfer only uses that every legal occupation vector extends
to a satisfying assignment.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import time
from pathlib import Path
from typing import Dict, Iterable, List, Sequence, Tuple


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def row_hash(rows: Sequence[Tuple[int, int]]) -> str:
    return hashlib.sha256(';'.join(f'{int(m)}:{int(c)}' for m, c in rows).encode()).hexdigest()


def run_cmd(args: List[str], timeout: int) -> Dict:
    t0 = time.time()
    try:
        p = subprocess.run(args, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=timeout)
        return {
            'args': args,
            'returncode': p.returncode,
            'stdout_tail': p.stdout[-6000:],
            'stderr_tail': p.stderr[-6000:],
            'elapsed_sec': time.time() - t0,
            'timeout': False,
        }
    except subprocess.TimeoutExpired as e:
        return {
            'args': args,
            'returncode': None,
            'stdout_tail': (e.stdout or '')[-6000:] if isinstance(e.stdout, str) else '',
            'stderr_tail': (e.stderr or '')[-6000:] if isinstance(e.stderr, str) else '',
            'elapsed_sec': time.time() - t0,
            'timeout': True,
        }


class CNFBuilder:
    def __init__(self, top: int):
        self.top = int(top)
        self.clauses: List[List[int]] = []
        self.stats: Dict[str, int] = {}
        self.ranges: List[Dict] = []

    def new_var(self) -> int:
        self.top += 1
        return self.top

    def add(self, clause: Sequence[int], tag: str) -> None:
        # Remove duplicated literals and skip tautological clauses.  This keeps
        # the DIMACS clause set mathematically identical to the intended clauses.
        seen = set(); out: List[int] = []
        for lit0 in clause:
            lit = int(lit0)
            if lit == 0:
                raise ValueError('zero literal')
            if -lit in seen:
                return
            if lit not in seen:
                seen.add(lit); out.append(lit)
        self.clauses.append(out)
        self.stats[tag] = self.stats.get(tag, 0) + 1

    def alloc_matrix(self, n: int, m: int, name: str, meta: Dict | None = None) -> List[List[int]]:
        start = self.top + 1
        mat = [[self.new_var() for _j in range(m + 1)] for _i in range(n + 1)]
        # Entry [0][*] and [*][0] are not used as variables by the encoders; they
        # are placeholders to make 1-indexed formulas readable.  They still got
        # variable ids, so record them as reserved.  This is harmless and keeps
        # the range contiguous for easy auditing.
        end = self.top
        rec = {'name': name, 'start_var': start, 'end_var': end, 'n_prefix': n, 'thresholds': m}
        if meta:
            rec.update(meta)
        self.ranges.append(rec)
        return mat

    def write_dimacs(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open('wt') as f:
            f.write(f'p cnf {self.top} {len(self.clauses)}\n')
            for cl in self.clauses:
                if cl:
                    f.write(' '.join(map(str, cl)) + ' 0\n')
                else:
                    f.write('0\n')


def count_var(p0: int, ell: int, L: int) -> int:
    # p0 is zero-based quotient point index; ell is 1..L.
    return p0 * L + ell


def add_row_atmost_forward(builder: CNFBuilder, lits: Sequence[int], cap: int, name: str) -> Dict:
    """Forward prefix-threshold encoding of sum(lits) <= cap.

    Auxiliary y[i,j] means: among the first i literals in this row, at least j
    are true, for j=1..cap+1.  The clauses force y whenever the prefix contains
    enough true inputs.  The unit -y[n,cap+1] therefore forbids cap+1 true inputs.
    If the row occupation is <= cap, the prefix-count assignment satisfies all
    clauses.
    """
    n = len(lits)
    if cap >= n:
        return {'name': name, 'kind': 'row_atmost_forward', 'n_lits': n, 'cap': cap, 'skipped': True, 'aux_vars': 0, 'clauses_before': len(builder.clauses), 'clauses_after': len(builder.clauses)}
    before_top = builder.top; before_clauses = len(builder.clauses)
    if cap < 0:
        builder.add([], 'row_negative_empty')
    elif cap == 0:
        for x in lits:
            builder.add([-int(x)], 'row_cap0_units')
    else:
        Kp = int(cap) + 1
        y = builder.alloc_matrix(n, Kp, name, {'kind': 'row_atmost_forward', 'cap': cap, 'n_lits': n})
        # i=1..n, j=1..Kp.  y[i][j] is 1-indexed in both coordinates.
        for i, x0 in enumerate(lits, start=1):
            x = int(x0)
            builder.add([-x, y[i][1]], 'row_x_implies_ge1')
            if i > 1:
                for j in range(1, Kp + 1):
                    builder.add([-y[i - 1][j], y[i][j]], 'row_prefix_monotone')
                for j in range(2, Kp + 1):
                    builder.add([-x, -y[i - 1][j - 1], y[i][j]], 'row_prefix_increment')
        builder.add([-y[n][Kp]], 'row_atmost_terminal')
    return {'name': name, 'kind': 'row_atmost_forward', 'n_lits': n, 'cap': cap, 'skipped': False, 'aux_vars': builder.top - before_top, 'clauses_before': before_clauses, 'clauses_after': len(builder.clauses)}


def add_total_exact_prefix(builder: CNFBuilder, lits: Sequence[int], L: int) -> Dict:
    """Exact prefix-threshold counter for sum(lits)=L.

    y[i,j] means at least j of the first i literals are true, for j=1..L+1.
    The four implication families encode the recurrence

        y[i,j] = y[i-1,j] OR (lits[i] AND y[i-1,j-1]).

    Boundary constants are y[0,0]=true, y[0,j>0]=false, y[i,0]=true.  Units
    y[n,L] and -y[n,L+1] enforce exact total L.  The prefix-count assignment for
    any input of weight exactly L satisfies every clause.
    """
    n = len(lits); Kp = int(L) + 1
    before_top = builder.top; before_clauses = len(builder.clauses)
    y = builder.alloc_matrix(n, Kp, 'total_exact_prefix', {'kind': 'total_exact_prefix', 'target': L, 'n_lits': n})

    def prev_var(i_minus_1: int, j: int):
        if j == 0:
            return True
        if i_minus_1 == 0:
            return False
        return y[i_minus_1][j]

    def add_or_with_constants(neg_y: int, terms: Sequence[object], tag: str) -> None:
        clause = [neg_y]
        for t in terms:
            if t is True:
                return
            if t is False:
                continue
            clause.append(int(t))
        builder.add(clause, tag)

    for i, x0 in enumerate(lits, start=1):
        x = int(x0)
        # Forward implications.
        builder.add([-x, y[i][1]], 'total_x_implies_ge1')
        for j in range(1, Kp + 1):
            pv = prev_var(i - 1, j)
            if pv is True:
                builder.add([y[i][j]], 'total_prev_true_unit')
            elif pv is not False:
                builder.add([-int(pv), y[i][j]], 'total_prefix_monotone')
        for j in range(2, Kp + 1):
            pm = prev_var(i - 1, j - 1)
            if pm is True:
                builder.add([-x, y[i][j]], 'total_increment_from_true_boundary')
            elif pm is not False:
                builder.add([-x, -int(pm), y[i][j]], 'total_prefix_increment')
        # Reverse implications for exactness.
        for j in range(1, Kp + 1):
            pv = prev_var(i - 1, j)
            pm = prev_var(i - 1, j - 1)
            add_or_with_constants(-y[i][j], [pv, x], 'total_reverse_prev_or_x')
            add_or_with_constants(-y[i][j], [pv, pm], 'total_reverse_prev_or_prevminus')
    builder.add([y[n][L]], 'total_lower_unit')
    builder.add([-y[n][L + 1]], 'total_upper_unit')
    return {'name': 'total_exact_prefix', 'kind': 'total_exact_prefix', 'n_lits': n, 'target': L, 'aux_vars': builder.top - before_top, 'clauses_before': before_clauses, 'clauses_after': len(builder.clauses)}


def load_core(core_json: Path) -> Tuple[List[Tuple[int, int]], int, int, Dict]:
    d = json.loads(core_json.read_text())
    L = int(d.get('old_lb', d.get('L', 18)))
    k = int(d.get('quotient_dim', d.get('k', 7)))
    row_key = 'shrunk_rows' if d.get('shrunk_rows') else 'selected_core_rows'
    rows = [(int(r['mask']), int(r['cap'])) for r in d[row_key]]
    meta = {
        'source_core': str(core_json),
        'source_schema': d.get('schema'),
        'source_index': d.get('index'),
        'source_row_key': row_key,
        'source_row_count': len(rows),
        'source_row_sha256': row_hash(rows),
        'cap_limit': d.get('cap_limit'),
    }
    return rows, k, L, meta


def encode(core_json: Path, cnf_path: Path, name: str | None = None, solve: bool = False, cadical_timeout: int = 300, drat_timeout: int = 300) -> Dict:
    t0 = time.time()
    rows, k, L, src = load_core(core_json)
    npts = (1 << k) - 1
    count_vars = npts * L
    b = CNFBuilder(top=count_vars)
    # u[p,ell+1] -> u[p,ell]
    for p in range(npts):
        for ell in range(1, L):
            b.add([-count_var(p, ell + 1, L), count_var(p, ell, L)], 'u_monotonicity')
    all_u = [count_var(p, ell, L) for p in range(npts) for ell in range(1, L + 1)]
    total_rec = add_total_exact_prefix(b, all_u, L)
    row_records = []
    for rno, (mask, cap) in enumerate(rows):
        lits = []
        for p in range(npts):
            if (int(mask) >> p) & 1:
                for ell in range(1, L + 1):
                    lits.append(count_var(p, ell, L))
        row_records.append(add_row_atmost_forward(b, lits, int(cap), f'row_{rno}_mask_{mask}_cap_{cap}'))
    b.write_dimacs(cnf_path)
    cnf_sha = sha256(cnf_path)
    cad = dr = None; verified = False
    drat_path = cnf_path.with_suffix('.drat')
    if solve:
        cad = run_cmd(['cadical', str(cnf_path), str(drat_path)], cadical_timeout)
        if cad['returncode'] == 20 and drat_path.exists():
            dr = run_cmd(['drat-trim', str(cnf_path), str(drat_path)], drat_timeout)
            verified = (dr['returncode'] == 0 and 's VERIFIED' in dr.get('stdout_tail', ''))
    out = {
        'schema': 's0908_transparent_unary_dim2_cnf_v1',
        'meaning': 'Transparent unary-count CNF with explicit prefix-counter lifting property for one dim-2 occupation core. A legal integer occupation vector of total L satisfying the source rows extends to this CNF by u[p,ell]=(ell<=x_p) and prefix-threshold auxiliary values.',
        'source': src,
        'k': k,
        'L': L,
        'npts': npts,
        'count_variables': count_vars,
        'cnf_path': str(cnf_path),
        'cnf_sha256': cnf_sha,
        'vars': b.top,
        'clauses': len(b.clauses),
        'stats': dict(sorted(b.stats.items())),
        'total_counter_record': total_rec,
        'row_count': len(rows),
        'row_aux_total': sum(int(r['aux_vars']) for r in row_records),
        'row_record_head': row_records[:12],
        'aux_ranges_head': b.ranges[:20],
        'aux_range_count': len(b.ranges),
        'drat_path': str(drat_path),
        'drat_sha256': sha256(drat_path) if drat_path.exists() else None,
        'cadical_returncode': None if cad is None else cad.get('returncode'),
        'drat_returncode': None if dr is None else dr.get('returncode'),
        'drat_verified': verified,
        'cadical': cad,
        'drat_trim': dr,
        'elapsed_sec': time.time() - t0,
    }
    meta_path = cnf_path.with_suffix('.transparent_meta.json')
    meta_path.write_text(json.dumps(out, indent=2, sort_keys=True) + '\n')
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--core-json', type=Path, required=True)
    ap.add_argument('--outdir', type=Path, required=True)
    ap.add_argument('--name', default=None)
    ap.add_argument('--solve', action='store_true')
    ap.add_argument('--cadical-timeout', type=int, default=300)
    ap.add_argument('--drat-timeout', type=int, default=300)
    args = ap.parse_args(); args.outdir.mkdir(parents=True, exist_ok=True)
    stem = args.name or args.core_json.stem.replace('_core', '_transparent_unary')
    out = encode(args.core_json, args.outdir / f'{stem}.cnf', stem, args.solve, args.cadical_timeout, args.drat_timeout)
    print(json.dumps({
        'status': 'ok',
        'meta': str(Path(out['cnf_path']).with_suffix('.transparent_meta.json')),
        'cnf': out['cnf_path'],
        'vars': out['vars'],
        'clauses': out['clauses'],
        'cadical': out['cadical_returncode'],
        'drat': out['drat_returncode'],
        'verified': out['drat_verified'],
        'elapsed_sec': out['elapsed_sec'],
    }, indent=2, sort_keys=True))


if __name__ == '__main__':
    main()
