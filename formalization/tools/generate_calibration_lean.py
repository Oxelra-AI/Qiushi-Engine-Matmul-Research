"""Generate literal calibration inputs; Lean, not this generator, proves checks."""

import argparse
import json
from pathlib import Path
import sys

from replay_occupation_calibration import digest, load_module, require


def vector(xs):
    return "![" + ", ".join(map(str, xs)) + "]"


def generate(repo, out):
    proof = repo / "proof"
    receipts = {r["path"]: r["sha256"] for r in
                json.loads((proof / "manifest.json").read_text())["files"]}

    def read(relative):
        path = proof / relative
        require(digest(path) == receipts[relative], f"hash mismatch: {relative}")
        return json.loads(path.read_text())

    summary = read("assets/occupation/data/dim2_independent/independent_semantics_summary.json")
    later = read("assets/occupation/data/dim2_independent/orbit491_target19_long.json")
    control = repo / "research/materials/quotient_cores/results/pivot_fixed/pivot17_rank23_transformed_control.json"
    require(digest(control) == "5221a6ef2e8d7398c02a83a37532da0acc18883c29f51980ad17cea75923bc70",
            "unexpected relocated fixture bytes")
    terms = json.loads(control.read_text())["terms"]
    sem = load_module(proof / "assets/occupation/scripts/dim2_independent_semantics.py")
    lines = ["import QiushiDefs", "", "namespace QiushiMatmul.Calibration", "",
             "/- Generated by tools/generate_calibration_lean.py. Literal inputs, not L0 facts.",
             "   The relocated tensor fixture differs in bytes from the historical receipt;",
             "   its full tensor identity and actual quotient projections are proved separately. -/", ""]
    for j, slot in enumerate("ABC"):
        lines += [f"def fixture{slot}Code : Fin 23 → Nat := {vector(t[j] for t in terms)}", ""]
    records = summary["results"]
    require([r["cert_index"] for r in records] == list(range(484, 492)), "orbit order")
    bases = [r["W_basis_from_orbit"] for r in records]
    lines += ["def planeBasis : Fin 8 → List Nat := " + vector(bases), "",
              "def freeBit : Fin 8 → Fin 7 → Nat := " +
              vector(vector(sem.free_bits(b)) for b in bases), ""]
    witnesses = []
    projections = []
    mass19 = []
    mass23 = []
    def mass_expr(qs):
        return "(fun m => " + " + (".join(f"(if m.testBit {q} then 1 else 0)" for q in qs) + " + 0" + ")" * (len(qs) - 1) + ")"
    for record, basis in zip(records, bases):
        witness = later["solve"] if record["cert_index"] == 491 else record["target_ladder"]["19"]
        qs = [q - 1 for q, count in witness["solution_head"] for _ in range(count)]
        require(len(qs) == 19 and all(0 <= q < 127 for q in qs), "witness domain")
        witnesses.append(vector(qs))
        mass19.append(mass_expr(qs))
        ps = [sem.quotient_coord(t[0], basis, sem.free_bits(basis)) - 1 for t in terms]
        require(len(ps) == 23 and all(0 <= q < 127 for q in ps), "projection domain")
        projections.append(vector(ps))
        mass23.append(mass_expr(ps))
    lines += ["/-- Public direction q is stored as q - 1. Repetitions are multiplicities. -/",
              "def target19Points : Fin 8 → Fin 19 → Fin 127 := " + vector(witnesses), "",
              "/-- In the original tensor term order, not sorted support order. -/",
              "def projectedPoints : Fin 8 → Fin 23 → Fin 127 := " + vector(projections), "",
              "/-- Unrolled evaluators; their equality to the occupation sum is proved in Formula. -/",
              "def mass19Eval : Fin 8 → Nat → Nat := " + vector(mass19), "",
              "def mass23Eval : Fin 8 → Nat → Nat := " + vector(mass23), "",
              "end QiushiMatmul.Calibration", ""]
    (out / "QiushiCalibrationData.lean").write_text("\n".join(lines))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    sys.dont_write_bytecode = True
    generate(args.repo.resolve(), args.output.resolve())
