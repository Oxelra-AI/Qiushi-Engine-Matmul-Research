r"""analysis: corrected evaluation of E11-core and rep2 saturation candidates.

This script fixes three interpretation hazards from analysis.

1.  The analysis E11-core separator counted only Wang rows generated by spans
    of at most five selected points.  Here we scan the complete core table of
    all 417,199 subspaces of F2^8, derived from the full Wang LUT.

2.  The E11-core construction search in analysis used 19 distinct Boolean
    A-points.  The complete scanner and positive control below are multiset
    aware, because a genuine tensor decomposition may repeat projective
    A-directions unless a separate argument excludes multiplicity.

3.  Saturated contractions force not only term-wise membership in row/column
    spaces, but the existence of independent representatives.  For a saturated
    contraction with participating terms I and rank |I|, the family of B-domain
    subspaces (and separately C-domain subspaces) must admit an independent
    transversal.  By Rado's theorem this is equivalent to

        dim(sum_{s in J} D_s) >= |J| for every J subset I.

The script validates the corrected machinery on the genuine cn122 E11-core
restriction: quotient all 23 A-factors, discard only zero images, and retain the
21 surviving terms with multiplicities and their B/C factors.
"""
