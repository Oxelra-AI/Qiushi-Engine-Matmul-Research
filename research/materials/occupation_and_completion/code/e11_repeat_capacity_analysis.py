#!/usr/bin/env python3
"""Analyze which repeated quotient A-directions are allowed by Wang occupancy.

For a length-19 E11 core CPD, occupancy constraints are multiset constraints.
This script extracts the caps of all quotient lines and small subspaces from the
Wang LUT to determine whether repeated A-directions can be ignored, reduced to a
single duplicated orbit, or require a separate multiset enumeration.
"""
from __future__ import annotations

import json, sys, itertools
from collections import Counter, defaultdict
from pathlib import Path

S04 = Path("scripts")
if str(S04) not in sys.path: sys.path.insert(0, str(S04))
from wang_capacity_lazy import rref_basis, unpack_basis, pack_basis  # type: ignore
from core_capacity_from_wang_lut import load_lut  # type: ignore

LUT = Path("data/wang_f2_lb20/wang_subspace_lut.pkl")
OUTDIR = Path("data/wang_validation")
OUTDIR.mkdir(parents=True, exist_ok=True)
MASK9=(1<<9)-1
N=19

def contains_e11(k:int)->bool:
    d=k&0xF
    return d>0 and (((k>>(4+9*(d-1)))&MASK9)==1)

def key9_to_basis8(k:int):
    raw=[]
    for b in unpack_basis(k):
        if b==1: continue
        q=int(b)
        if q&1: q^=1
        q8=0
        for bit in range(1,9):
            if (q>>bit)&1: q8 |= 1<<(bit-1)
        if q8: raw.append(q8)
    return tuple(rref_basis(raw,n=8)) if raw else tuple()

def key8_from_basis(basis):
    return pack_basis(rref_basis(list(basis), n=8))

def points_of_basis(basis):
    pts=[]; d=len(basis)
    for m in range(1,1<<d):
        v=0
        for i,b in enumerate(basis):
            if (m>>i)&1: v^=b
        pts.append(v)
    return sorted(pts)

def main():
    lut,_=load_lut(LUT)
    cap_by_key8={}
    lb_by_key8={}
    for k,lb in lut.items():
        if not contains_e11(int(k)): continue
        b=key9_to_basis8(int(k))
        key8=key8_from_basis(b)
        cap_by_key8[key8]=N-int(lb)
        lb_by_key8[key8]=int(lb)
    # line caps
    cap2_points=[]
    line_recs=[]
    for p in range(1,256):
        key=key8_from_basis([p])
        cap=cap_by_key8[key]; lb=lb_by_key8[key]
        line_recs.append({"p":p,"cap":cap,"lb":lb})
        if cap>=2: cap2_points.append(p)
    # pair caps among repeatable points
    pair_recs=[]
    for a,b in itertools.combinations(cap2_points,2):
        key=key8_from_basis([a,b])
        cap=cap_by_key8[key]; lb=lb_by_key8[key]
        pair_recs.append({"points":[a,b],"cap":cap,"lb":lb,"pair_occ_if_both_doubled":4,"both_doubled_allowed_by_pair":4<=cap})
    # all subspaces generated by subsets of repeatable points, compute maximum total duplicate multiplicity if all subset points doubled.
    subset_recs=[]
    for r in range(1,len(cap2_points)+1):
        for sub in itertools.combinations(cap2_points,r):
            basis=tuple(rref_basis(list(sub), n=8))
            key=key8_from_basis(basis)
            pts=set(points_of_basis(basis))
            selected=set(sub)
            cap=cap_by_key8[key]; lb=lb_by_key8[key]
            occ=2*len(selected)  # if exactly these repeatable points have multiplicity 2
            subset_recs.append({"repeat_points":list(sub),"span_dim":len(basis),"span_points":len(pts),"cap":cap,"lb":lb,"occ_if_all_doubled":occ,"allowed_by_span":occ<=cap})
    out={
        "status":"ok",
        "line_cap_hist":dict(sorted(Counter(r['cap'] for r in line_recs).items())),
        "repeatable_points_cap_ge2":cap2_points,
        "repeatable_point_count":len(cap2_points),
        "line_records_cap_ge2":[r for r in line_recs if r['cap']>=2],
        "pair_cap_hist_among_repeatable":dict(sorted(Counter(r['cap'] for r in pair_recs).items())),
        "pairs_allowing_two_doubled":[r for r in pair_recs if r['both_doubled_allowed_by_pair']],
        "subset_allowed_count_by_size":{f"size{a}_allowed{b}": int(c) for (a,b),c in sorted(Counter((len(r['repeat_points']), r['allowed_by_span']) for r in subset_recs).items(), key=lambda kv: str(kv[0]))},
        "subset_records":subset_recs,
    }
    path=OUTDIR/"e11_repeat_capacity_analysis.json"
    path.write_text(json.dumps(out, indent=2, sort_keys=True)+"\n")
    print(json.dumps({k:out[k] for k in ["line_cap_hist","repeatable_points_cap_ge2","pair_cap_hist_among_repeatable","pairs_allowing_two_doubled","subset_allowed_count_by_size"]}, indent=2, sort_keys=True))
    print(f"Saved {path}")

if __name__=='__main__': main()
