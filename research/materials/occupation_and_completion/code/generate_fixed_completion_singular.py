#!/usr/bin/env python3
"""Generate Singular ideals for analysis fixed-completion compatibility.

The ideal is N * vec(v v^T_tau) = 0, where N is a left-nullspace basis of
span(Laderman-free-slots, L1).  Its projective points are tau-fixed generators
whose rank-one slice matrix lies in F + L1.
"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np

SCRIPT_DIR=Path(__file__).resolve().parent
WS=SCRIPT_DIR.parent
DATA=WS/"data"/"fixed_completion_enum"
DATA.mkdir(parents=True,exist_ok=True)
P=5; IROOT=2

def inv(a,p=P): return pow(int(a)%p,-1,p)
def mod(A,p=P): return np.asarray(A,dtype=object)%p

def mat_inv(A,p=P):
    A=mod(A,p); n=A.shape[0]
    aug=np.concatenate([A.copy(),np.eye(n,dtype=object)],axis=1)%p
    r=0
    for c in range(n):
        piv=next((i for i in range(r,n) if int(aug[i,c])%p),None)
        if piv is None: raise ValueError('singular')
        if piv!=r: aug[[r,piv]]=aug[[piv,r]]
        aug[r,:]=(aug[r,:]*inv(aug[r,c],p))%p
        for i in range(n):
            if i!=r and int(aug[i,c])%p:
                aug[i,:]=(aug[i,:]-aug[i,c]*aug[r,:])%p
        r+=1
    return aug[:,n:]%p

def rref(M,p=P):
    M=mod(M,p).copy(); m,n=M.shape; r=0; piv=[]
    for c in range(n):
        pivrow=next((i for i in range(r,m) if int(M[i,c])%p),None)
        if pivrow is None: continue
        if pivrow!=r: M[[r,pivrow]]=M[[pivrow,r]]
        M[r,:]=(M[r,:]*inv(M[r,c],p))%p
        for i in range(m):
            if i!=r and int(M[i,c])%p:
                M[i,:]=(M[i,:]-M[i,c]*M[r,:])%p
        piv.append(c); r+=1
    return M,r,piv

def row_basis(M,p=P):
    R,r,piv=rref(M,p); return R[:r],piv

def nullspace_rows(M,p=P):
    R,r,piv=rref(M,p); n=M.shape[1]; free=[c for c in range(n) if c not in set(piv)]
    out=[]
    for f in free:
        x=np.zeros(n,dtype=object); x[f]=1
        for row,col in enumerate(piv): x[col]=(-R[row,f])%p
        out.append(x%p)
    return np.vstack(out)%p if out else np.zeros((0,n),dtype=object)

# Load and transport
src_path=SCRIPT_DIR/"laderman_tau_decomp.py"
src=src_path.read_text(); prefix=src.split('print(f"Sum matches T333')[0]
ns={"__file__":str(src_path),"__name__":"defs_only"}
exec(compile(prefix,str(src_path),"exec"),ns)
terms=[(mod(a),mod(b),mod(c)) for a,b,c in ns['terms']]
eps1=mod(ns['eps1']); pi12=mod(ns['pi12'])
Q=eps1@pi12%P; R=np.diag([IROOT,1,1]).astype(object)%P
Qinv=mat_inv(Q); Rinv=mat_inv(R)
def g(a,b,c): return (a@Qinv%P, Q@b@Rinv%P, R@c%P)
transported=[g(a,b,c) for a,b,c in terms]
free_pairs=[(1,4),(2,5),(6,15),(7,17),(8,16),(10,13),(12,14),(19,21)]
free_slots=[i for pair in free_pairs for i in pair]

def vec9(M): return np.asarray(M,dtype=object).reshape(9)%P
X=[]
for idx in free_slots:
    _,b,c=transported[idx]
    X.append(np.outer(vec9(b),vec9(c)).reshape(81)%P)
F=np.vstack(X)%P
L=[]
for a in range(3):
    for b in range(3):
        M=np.zeros((9,9),dtype=object)
        for k in range(3): M[3*b+k,3*k+a]=1
        L.append(M.reshape(81))
L=np.vstack(L)%P
S_basis,_=row_basis(np.vstack([F,L])%P)
N=nullspace_rows(S_basis)

# fixed x(v)=v vec(V^T)^T, coordinate index in flattened 9x9 row-major: row i, col transpose(j)
def trans_idx(j):
    r=j//3; c=j%3
    return 3*c+r
quad_coeffs=[]
for row in N:
    # coefficients for monomials x_i*x_j, i,j 0..8. keep full ordered form first.
    terms_coeff=[]
    for i in range(9):
        for j in range(9):
            coeff=int(row[9*i+trans_idx(j)])%P
            if coeff:
                terms_coeff.append((coeff,i,j))
    if terms_coeff:
        quad_coeffs.append(terms_coeff)

vars=",".join(f"x{i}" for i in range(9))
polys=[]
for coeffs in quad_coeffs:
    pieces=[]
    for coeff,i,j in coeffs:
        term=f"x{i}*x{j}"
        if coeff==1: pieces.append(term)
        else: pieces.append(f"{coeff}*{term}")
    polys.append("+".join(pieces))
ideal="I="+",\n".join(polys)+";"
# Include commands for Groebner basis, projective dimension/degree, radical-ish point checks by adding chart xk=1.
content=f"""// Generated by generate_fixed_completion_singular.py
ring r={P},({vars}),dp;
ideal {ideal}
ideal J=std(I);
print(\"num_generators\"); size(I);
print(\"affine_dim\"); dim(J);
print(\"degree\"); degree(J);
print(\"lead_std_size\"); size(J);
// chart dimensions/degrees for x_k=1 to compare with projective enumeration
for (int k=0; k<9; k=k+1) {{
  ideal C=I,x(k+1)-1;
  ideal JC=std(C);
  print(\"chart\"); k; dim(JC); degree(JC); size(JC);
}}
quit;
"""
path=DATA/"fixed_completion_F5.sing"
path.write_text(content)
meta={"p":P,"free_span_plus_L_rank":int(S_basis.shape[0]),"left_nullity":int(N.shape[0]),"nonzero_quadrics":len(quad_coeffs),"singular_file":str(path)}
(DATA/"fixed_completion_singular_meta.json").write_text(json.dumps(meta,indent=2)+"\n")
print(json.dumps(meta,indent=2))
print(f"SAVED {path}")
