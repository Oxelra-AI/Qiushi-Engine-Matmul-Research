#!/usr/bin/env python3
"""
analysis: Z4-equivariant m=4 exterior fiber correction and rank-10 residual instruments.

This script checks the symmetry explanation of the analysis tangent
space: the 10-dimensional tangent kernel of
    (A,B,C) in sl3^3 -> S4(A wedge B wedge C)
is exactly generated by
    * 8 internal SL3 recombinations of the three columns (A,B,C), and
    * 2 nontrivial centralizer-conjugation directions for a0.

It also anchors the corrected residual formula at the BILR point and computes
small exact modular tangent data for Z4-stable 10-cube orbit patterns.  These
pattern data are not nonexistence proofs; they make the next algebraic systems
explicit and help separate concise from automatically non-concise patterns.
"""
