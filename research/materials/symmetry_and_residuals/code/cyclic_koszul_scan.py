#!/usr/bin/env python3
"""
analysis: Corrected cyclic-outer algebra checks.

This script does three things tied to the characteristic-zero cyclic rank-22 line:

1.  Verifies the bookkeeping correction for the antisymmetric quotient:
    Lambda^3(gl_3) = Lambda^3(sl_3) plus I wedge Lambda^2(sl_3), with dimensions
    84 = 56 + 28.  It computes the mixed trace-lift map for an m=4 exterior
    decomposition.

2.  Verifies local rigidity of a numerical rank-4 decomposition of the Cartan
    trivector omega: the Jacobian of
        (u_j,v_j,w_j)_{j=1}^4 -> sum_j u_j wedge v_j wedge w_j
    has rank 56, hence kernel dimension 40 = 4*dim(SL_3) + dim(PGL_3).

3.  Samples the true m=4 family generated by SL_3 basis changes in each 3-plane
    and trace lifts satisfying the 28 mixed equations, and computes the cubic
    Koszul/Young flattening
        Lambda^4 V \otimes V^* -> Lambda^5 V \otimes V
    for the symmetric residual cubic
        tr(M^3) - 3 sum_j l_{U_j} l_{V_j} l_{W_j}.
    For a Waring-rank-f cubic, this flattening has rank at most 70 f.  Therefore
    rank > 700 rules out Waring rank <= 10 for the sampled member of the m=4
    family.  This is numerical evidence and a target for an exact algebraic proof,
    not a global proof by itself.
"""
from __future__ import annotations

import argparse, itertools, json, math
from pathlib import Path
import numpy as np

WS = Path(__file__).resolve().parent.parent
OUT = WS / "data" / "cyclic_koszul"
OUT.mkdir(parents=True, exist_ok=True)

SL_N = 8
GL_N = 9
TRIPLES8 = list(itertools.combinations(range(SL_N), 3))
TRIPLE8_IDX = {t: i for i, t in enumerate(TRIPLES8)}
PAIRS8 = list(itertools.combinations(range(SL_N), 2))
PAIR8_IDX = {p: i for i, p in enumerate(PAIRS8)}
SUB4 = list(itertools.combinations(range(GL_N), 4))
SUB5 = list(itertools.combinations(range(GL_N), 5))
SUB5_IDX = {s: i for i, s in enumerate(SUB5)}


def sl3_to_gl3_matrix() -> np.ndarray:
    """Columns are the analysis sl_3 basis in row-major gl_3 coordinates."""
    B = np.zeros((9, 8), dtype=float)
    B[1, 0] = 1.0  # E01
    B[2, 1] = 1.0  # E02
    B[3, 2] = 1.0  # E10
    B[5, 3] = 1.0  # E12
    B[6, 4] = 1.0  # E20
    B[7, 5] = 1.0  # E21
    B[0, 6] = 1.0; B[4, 6] = -1.0  # E00-E11
    B[4, 7] = 1.0; B[8, 7] = -1.0  # E11-E22
    return B

B_SL_TO_GL = sl3_to_gl3_matrix()
IDENTITY_GL = np.zeros(9, dtype=float)
IDENTITY_GL[[0, 4, 8]] = 1.0


def sort_sign(seq) -> int:
    inv = 0
    for i in range(len(seq)):
        for j in range(i + 1, len(seq)):
            if seq[i] > seq[j]:
                inv += 1
    return -1 if (inv & 1) else 1


def wedge3_sl(u: np.ndarray, v: np.ndarray, w: np.ndarray) -> np.ndarray:
    out = np.zeros(len(TRIPLES8), dtype=float)
    for r, (a, b, c) in enumerate(TRIPLES8):
        out[r] = (
            u[a] * (v[b] * w[c] - v[c] * w[b])
            - u[b] * (v[a] * w[c] - v[c] * w[a])
            + u[c] * (v[a] * w[b] - v[b] * w[a])
        )
    return out


def wedge2_sl(u: np.ndarray, v: np.ndarray) -> np.ndarray:
    out = np.zeros(len(PAIRS8), dtype=float)
    for r, (a, b) in enumerate(PAIRS8):
        out[r] = u[a] * v[b] - u[b] * v[a]
    return out


def build_omega_sl3() -> np.ndarray:
    # Same basis/order as analysis exact_exterior_analysis.json.
    omega = np.zeros(len(TRIPLES8), dtype=float)
    terms = {
        (0, 2, 6): 3.0,
        (0, 3, 4): 3.0,
        (1, 2, 5): -3.0,
        (1, 4, 6): 3.0,
        (1, 4, 7): 3.0,
        (3, 5, 7): 3.0,
    }
    for t, c in terms.items():
        omega[TRIPLE8_IDX[t]] = c
    return omega


def load_decomposition() -> np.ndarray:
    path = WS / "data" / "exterior_rank4" / "exterior_rank4_decomposition.json"
    data = json.loads(path.read_text())
    arr = np.zeros((4, 3, 8), dtype=float)
    for j, term in enumerate(data["decomposition"]):
        arr[j, 0, :] = term["u"]
        arr[j, 1, :] = term["v"]
        arr[j, 2, :] = term["w"]
    return arr


def exterior_sum(decomp: np.ndarray) -> np.ndarray:
    s = np.zeros(len(TRIPLES8), dtype=float)
    for j in range(decomp.shape[0]):
        s += wedge3_sl(decomp[j, 0], decomp[j, 1], decomp[j, 2])
    return s


def exterior_jacobian(decomp: np.ndarray) -> np.ndarray:
    """Finite-dimensional exact formula for derivative of the four-wedge map."""
    m = decomp.shape[0]
    J = np.zeros((len(TRIPLES8), m * 3 * 8), dtype=float)
    for j in range(m):
        u, v, w = decomp[j]
        for coord in range(8):
            e = np.zeros(8); e[coord] = 1.0
            J[:, (j * 3 + 0) * 8 + coord] = wedge3_sl(e, v, w)
            J[:, (j * 3 + 1) * 8 + coord] = wedge3_sl(u, e, w)
            J[:, (j * 3 + 2) * 8 + coord] = wedge3_sl(u, v, e)
    return J


def mixed_trace_matrix(decomp: np.ndarray) -> np.ndarray:
    """28 x (3m) matrix for I wedge Lambda^2(sl_3) trace-lift equations."""
    m = decomp.shape[0]
    M = np.zeros((len(PAIRS8), 3 * m), dtype=float)
    for j in range(m):
        u, v, w = decomp[j]
        # (u+aI)^(v+bI)^(w+cI) mixed coefficient is
        # I^( a v^w - b u^w + c u^v ).
        M[:, 3*j + 0] = wedge2_sl(v, w)
        M[:, 3*j + 1] = -wedge2_sl(u, w)
        M[:, 3*j + 2] = wedge2_sl(u, v)
    return M


def nullspace_svd(A: np.ndarray, tol=1e-10) -> np.ndarray:
    U, S, Vt = np.linalg.svd(A, full_matrices=True)
    if S.size == 0:
        rank = 0
    else:
        rank = int(np.sum(S > tol * max(A.shape) * S[0]))
    return Vt[rank:].T


def random_sl3_matrix(rng: np.random.Generator, scale=0.6) -> np.ndarray:
    """Random real 3x3 matrix with determinant 1."""
    while True:
        A = np.eye(3) + scale * rng.standard_normal((3, 3))
        d = np.linalg.det(A)
        if abs(d) > 1e-4:
            c = np.cbrt(d)
            A = A / c
            # numerical correction makes determinant extremely close to one
            return A


def transform_decomp_by_term_sl3(decomp: np.ndarray, rng: np.random.Generator, scale=0.6) -> np.ndarray:
    out = decomp.copy()
    for j in range(out.shape[0]):
        A = random_sl3_matrix(rng, scale=scale)
        out[j] = A @ out[j]
    return out


def target_trM3_symmetric_tensor() -> np.ndarray:
    """Symmetric tensor representing polynomial tr(M^3) in row-major variables."""
    mono = {}
    for a, b, c in itertools.product(range(3), repeat=3):
        inds = [3*a + b, 3*b + c, 3*c + a]
        key = tuple(sorted(inds))
        mono[key] = mono.get(key, 0.0) + 1.0
    T = np.zeros((9, 9, 9), dtype=float)
    for key, coef in mono.items():
        perms = sorted(set(itertools.permutations(key)))
        val = coef / len(perms)
        for p in perms:
            T[p] = val
    return T

TARGET_CUBIC = target_trM3_symmetric_tensor()


def sym_outer3(u: np.ndarray, v: np.ndarray, w: np.ndarray) -> np.ndarray:
    T = np.zeros((9, 9, 9), dtype=float)
    vecs = [u, v, w]
    for perm in itertools.permutations(range(3)):
        T += np.einsum('i,j,k->ijk', vecs[perm[0]], vecs[perm[1]], vecs[perm[2]])
    return T / 6.0


def residual_cubic_tensor(decomp_sl: np.ndarray, trace_coeffs: np.ndarray | None = None) -> np.ndarray:
    """Symmetric residual cubic tensor for the m free cyclic orbits."""
    m = decomp_sl.shape[0]
    if trace_coeffs is None:
        trace_coeffs = np.zeros(3*m)
    R = TARGET_CUBIC.copy()
    for j in range(m):
        u = B_SL_TO_GL @ decomp_sl[j, 0] + trace_coeffs[3*j + 0] * IDENTITY_GL
        v = B_SL_TO_GL @ decomp_sl[j, 1] + trace_coeffs[3*j + 1] * IDENTITY_GL
        w = B_SL_TO_GL @ decomp_sl[j, 2] + trace_coeffs[3*j + 2] * IDENTITY_GL
        R -= 3.0 * sym_outer3(u, v, w)
    return R


def polynomial_value_from_tensor(T: np.ndarray, x: np.ndarray) -> float:
    return float(np.einsum('ijk,i,j,k', T, x, x, x))


def koszul_matrix_cubic(T: np.ndarray, p: int = 4) -> np.ndarray:
    """Koszul flattening V* tensor Lambda^p V -> Lambda^{p+1}V tensor V.

    Column: (a, S), a in [0,n), S sorted p-subset.
    Row: (U, k), U sorted (p+1)-subset, k in [0,n).
    Entry: sum_i T[a,i,k] sign(e_i wedge e_S = sign e_U).
    """
    n = T.shape[0]
    subp = list(itertools.combinations(range(n), p))
    subp1 = list(itertools.combinations(range(n), p+1))
    subp1_idx = {s: i for i, s in enumerate(subp1)}
    M = np.zeros((len(subp1)*n, n*len(subp)), dtype=float)
    for a in range(n):
        for sidx, S in enumerate(subp):
            Sset = set(S)
            col = a * len(subp) + sidx
            for i in range(n):
                if i in Sset:
                    continue
                U = tuple(sorted((i,) + S))
                sign = -1 if (sum(1 for z in S if z < i) & 1) else 1
                row_base = subp1_idx[U] * n
                # vectorized over output k
                M[row_base:row_base+n, col] += sign * T[a, i, :]
    return M


def numerical_rank(M: np.ndarray, rtol=1e-9):
    s = np.linalg.svd(M, compute_uv=False)
    tol = rtol * max(M.shape) * (s[0] if s.size else 1.0)
    rank = int(np.sum(s > tol))
    return rank, float(s[0] if s.size else 0.0), float(s[rank-1] if rank else 0.0), float(s[rank] if rank < len(s) else 0.0)


def test_rank_one_koszul() -> int:
    rng = np.random.default_rng(123)
    v = rng.standard_normal(9)
    T = np.einsum('i,j,k->ijk', v, v, v)
    M = koszul_matrix_cubic(T, p=4)
    return numerical_rank(M, rtol=1e-10)[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--samples', type=int, default=12)
    ap.add_argument('--seed', type=int, default=3801)
    ap.add_argument('--trace-scale', type=float, default=1.0)
    ap.add_argument('--sl3-scale', type=float, default=0.55)
    ap.add_argument('--rank-tol', type=float, default=1e-9)
    args = ap.parse_args()

    rng = np.random.default_rng(args.seed)
    omega = build_omega_sl3()
    base = load_decomposition()
    base_err = float(np.max(np.abs(exterior_sum(base) - omega)))

    J = exterior_jacobian(base)
    J_rank, J_s0, J_slast, J_snext = numerical_rank(J, rtol=1e-10)
    mix_base = mixed_trace_matrix(base)
    mix_rank, mix_s0, mix_slast, mix_snext = numerical_rank(mix_base, rtol=1e-10)
    mix_null = nullspace_svd(mix_base, tol=1e-10)

    rank_one_test = test_rank_one_koszul()

    records = []
    # sample 0 is base with zero trace; subsequent samples randomize SL3 and traces
    for sample in range(args.samples):
        if sample == 0:
            decomp = base.copy()
            label = 'base_zero_trace'
        else:
            decomp = transform_decomp_by_term_sl3(base, rng, scale=args.sl3_scale)
            label = 'random_sl3_trace'
        ext_err = float(np.max(np.abs(exterior_sum(decomp) - omega)))
        Mmix = mixed_trace_matrix(decomp)
        mrank, _, _, _ = numerical_rank(Mmix, rtol=1e-10)
        NS = nullspace_svd(Mmix, tol=1e-10)
        if sample == 0 or NS.shape[1] == 0:
            tc = np.zeros(3 * decomp.shape[0])
        else:
            coeff = rng.standard_normal(NS.shape[1]) * args.trace_scale
            tc = NS @ coeff
        mixed_resid = float(np.max(np.abs(Mmix @ tc))) if tc.size else 0.0
        R = residual_cubic_tensor(decomp, tc)
        # sanity check polynomial value against direct formula at one random point
        x = rng.standard_normal(9)
        direct = polynomial_value_from_tensor(TARGET_CUBIC, x)
        for j in range(decomp.shape[0]):
            u = B_SL_TO_GL @ decomp[j, 0] + tc[3*j + 0] * IDENTITY_GL
            v = B_SL_TO_GL @ decomp[j, 1] + tc[3*j + 1] * IDENTITY_GL
            w = B_SL_TO_GL @ decomp[j, 2] + tc[3*j + 2] * IDENTITY_GL
            direct -= 3.0 * float(np.dot(u, x) * np.dot(v, x) * np.dot(w, x))
        tensor_val = polynomial_value_from_tensor(R, x)
        poly_err = abs(tensor_val - direct)
        K = koszul_matrix_cubic(R, p=4)
        krank, s0, slast, snext = numerical_rank(K, rtol=args.rank_tol)
        records.append({
            'sample': sample,
            'label': label,
            'exterior_max_error': ext_err,
            'mixed_matrix_rank': int(mrank),
            'mixed_nullity': int(NS.shape[1]),
            'mixed_residual_max': mixed_resid,
            'trace_norm': float(np.linalg.norm(tc)),
            'poly_sanity_error': float(poly_err),
            'koszul_rank': int(krank),
            'rank_over_700': bool(krank > 700),
            'rank_over_490': bool(krank > 490),
            'svd_largest': s0,
            'svd_last_above_tol': slast,
            'svd_first_below_tol': snext,
        })
        print(records[-1])

    summary = {
        'bookkeeping': {
            'dim_lambda3_gl3': math.comb(9, 3),
            'dim_lambda3_sl3': math.comb(8, 3),
            'dim_I_wedge_lambda2_sl3': math.comb(8, 2),
            'sum': math.comb(8, 3) + math.comb(8, 2),
        },
        'rank_one_koszul_rank_expected_70': int(rank_one_test),
        'base_exterior_max_error': base_err,
        'exterior_jacobian': {
            'rank': int(J_rank),
            'shape': list(J.shape),
            'kernel_dim': int(J.shape[1] - J_rank),
            'largest_sv': J_s0,
            'last_above_tol': J_slast,
            'first_below_tol': J_snext,
            'expected_rank': 56,
            'expected_kernel_dim': 40,
        },
        'base_mixed_trace_map': {
            'rank': int(mix_rank),
            'shape': list(mix_base.shape),
            'nullity': int(mix_null.shape[1]),
            'largest_sv': mix_s0,
            'last_above_tol': mix_slast,
            'first_below_tol': mix_snext,
        },
        'koszul_bound': {
            'map': 'Lambda^4 V tensor V* -> Lambda^5 V tensor V for cubics in 9 variables',
            'matrix_shape': [len(SUB5)*9, len(SUB4)*9],
            'rank_one_upper': 70,
            'rank_gt_700_implies_waring_rank_at_least_11': True,
            'rank_gt_490_implies_waring_rank_at_least_8': True,
        },
        'samples': records,
        'min_koszul_rank': int(min(r['koszul_rank'] for r in records)),
        'max_koszul_rank': int(max(r['koszul_rank'] for r in records)),
        'all_sampled_gt_700': bool(all(r['koszul_rank'] > 700 for r in records)),
    }
    out = OUT / 'cyclic_koszul_scan.json'
    out.write_text(json.dumps(summary, indent=2) + '\n')
    print(f"Saved {out}")

if __name__ == '__main__':
    main()
