#!/usr/bin/env python3
r"""analysis v2: strengthened order-7 diagonal-sandwich certificate over F2.

This script imports the GF(2) helpers from order7_family_certificate.py and
produces the theorem statement aligned with the actual proof:

There is no collection of at most 22 nonzero rank-one UV points whose span contains
L and whose terms are permuted by a diagonal order-7 sandwich subgroup
phi_{F,F,F} over F2.  Equivalently, no rank <=22 F2 decomposition of T_<3,3,3>
has this termwise diagonal order-7 sandwich symmetry (in the UV-span formulation).

The proof is pure finite linear algebra.  It first verifies the finite QMM action
convention by g_E T = T h_W.  It then uses sigma=sum_{k=0}^6 g_E^k, whose image is
Fix(g_E), and the 3-dimensional fixed slice space L0=L∩Fix(g_E).  The fixed
rank-one locus spans a 9-space B with B∩L0=0.  If S contains L and is generated by
f fixed rank-one points plus m seven-orbits, then for P=span(fixed points)
    P + L0 <= S∩Fix(g_E) = sigma(S),  but  dim sigma(S) <= dim P + m.
Thus m>=3.  For r<=20 this is impossible.  For r=21, m=3 and no fixed point;
each orbit sum would need to lie in L0, but the enumeration shows all such orbit
sums are zero.  For r=22, m=3 and f=1; for each fixed point p, each orbit sum
would need to lie in L0+<p>, but the enumeration shows all such orbit sums are
exactly p, so sigma(S)=<p> cannot contain L0.
"""

from __future__ import annotations

import json
import time
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

import order7_family_certificate as c


def enumerate_gl3_f2():
    mats = []
    for z in range(1 << 9):
        M = np.array([(z >> b) & 1 for b in range(9)], dtype=np.uint8).reshape(3, 3)
        if c.gf2_rank(M) == 3:
            mats.append(M)
    return mats


def mat_key(M):
    return bytes(np.array(M, dtype=np.uint8).reshape(-1).tolist())


def subgroup_generated_by(F):
    cur = np.eye(3, dtype=np.uint8)
    out = []
    for _ in range(7):
        out.append(mat_key(cur))
        cur = (F @ cur) & 1
    return frozenset(out)


def gl3_order7_conjugacy(F7):
    gl = enumerate_gl3_f2()
    order7_elems = []
    subgroups = set()
    for M in gl:
        if np.array_equal(c.gf2_matpow(M, 7), np.eye(3, dtype=np.uint8)) and not np.array_equal(M, np.eye(3, dtype=np.uint8)):
            # Exclude smaller order; over GL3(2), nonidentity satisfying x^7=1 has order 7.
            order7_elems.append(M)
            subgroups.add(subgroup_generated_by(M))
    target = subgroup_generated_by(F7)
    orbit = set()
    for G in gl:
        Gi = c.gf2_inv(G)
        conj_sub = set()
        for key in target:
            H = np.frombuffer(key, dtype=np.uint8).reshape(3, 3)
            conj_sub.add(mat_key((G @ H @ Gi) & 1))
        orbit.add(frozenset(conj_sub))
    return {
        "GL3F2_size": len(gl),
        "order7_element_count": len(order7_elems),
        "order7_subgroup_count": len(subgroups),
        "conjugates_of_selected_subgroup": len(orbit),
        "all_order7_subgroups_conjugate": orbit == subgroups,
    }


def main():
    t0 = time.time()
    out_dir = Path("data/order7_exhaustive")
    out_dir.mkdir(parents=True, exist_ok=True)

    T = c.build_T333_flat()
    L = T.T & 1
    Q = c.quotient_Q(T)
    Qp = c.right_inverse_Q(Q)

    F7 = np.array([[0, 0, 1], [1, 0, 1], [0, 1, 0]], dtype=np.uint8)
    M9, gE, hW = c.sandwich_actions(F7)
    gbar = (Q @ gE @ Qp) & 1

    action_checks = {
        "gE_T_equals_T_hW": bool(np.array_equal((gE @ T) & 1, (T @ hW) & 1)),
        "gbar_Q_equals_Q_gE": bool(np.array_equal((gbar @ Q) & 1, (Q @ gE) & 1)),
        "orders": {
            "F7": bool(np.array_equal(c.gf2_matpow(F7, 7), np.eye(3, dtype=np.uint8))),
            "M9": bool(np.array_equal(c.gf2_matpow(M9, 7), np.eye(9, dtype=np.uint8))),
            "gE": bool(np.array_equal(c.gf2_matpow(gE, 7), np.eye(81, dtype=np.uint8))),
            "hW": bool(np.array_equal(c.gf2_matpow(hW, 7), np.eye(9, dtype=np.uint8))),
            "gbar": bool(np.array_equal(c.gf2_matpow(gbar, 7), np.eye(72, dtype=np.uint8))),
        },
    }
    if not all([action_checks["gE_T_equals_T_hW"], action_checks["gbar_Q_equals_Q_gE"], *action_checks["orders"].values()]):
        raise AssertionError(f"action check failed: {action_checks}")

    fixE = c.gf2_nullspace((gE ^ np.eye(81, dtype=np.uint8)) & 1)
    _, fixE_dim, fix_pivots = c.gf2_rref(fixE)
    fixQ_dim = c.gf2_nullspace((gbar ^ np.eye(72, dtype=np.uint8)) & 1).shape[0]
    L0 = (c.gf2_nullspace((hW ^ np.eye(9, dtype=np.uint8)) & 1) @ L) & 1
    L0_basis, L0_dim, _ = c.gf2_rref(L0)
    L0_equals_intersection = (c.intersection_dim(L, fixE) == L0_dim) and (c.gf2_rank(np.vstack([fixE, L0_basis])) == fixE_dim)

    sigma = np.zeros((81, 81), dtype=np.uint8)
    pwr = np.eye(81, dtype=np.uint8)
    for _ in range(7):
        sigma ^= pwr
        pwr = (gE @ pwr) & 1
    sigma_checks = {
        "rank": int(c.gf2_rank(sigma)),
        "idempotent": bool(np.array_equal((sigma @ sigma) & 1, sigma)),
        "image_fixed_rank": int(c.gf2_rank(((gE ^ np.eye(81, dtype=np.uint8)) @ sigma) & 1)),
        "image_equals_FixE": bool(c.gf2_rank(sigma) == fixE_dim and c.gf2_rank(((gE ^ np.eye(81, dtype=np.uint8)) @ sigma) & 1) == 0),
    }

    print("Action, quotient, sigma checks passed")
    print("Fixed-space dims", {"FixE": fixE_dim, "L0": L0_dim, "FixE_mod_L": fixQ_dim, "L0_equals_intersection": L0_equals_intersection})

    pts = c.enumerate_rank_one()
    fixed_idx, free_orbits = c.classify_orbits(gE, pts, 7)
    fixed_pts = pts[fixed_idx]
    fixed_span_rank = c.gf2_rank(fixed_pts)
    fixed_L_intersection = c.intersection_dim(fixed_pts, L)
    fixed_L0_intersection = c.intersection_dim(fixed_pts, L0_basis)

    fixed_coord_map = {c.fixed_coord(pts[i], fix_pivots): local for local, i in enumerate(fixed_idx)}
    fixed_coords_unique = len(fixed_coord_map) == len(fixed_idx)
    L0_coords = c.span_all_ints([c.fixed_coord(v, fix_pivots) for v in L0_basis])

    orbit_profile = Counter()
    orbit_sum_in_L0_nonzero = 0
    filtered_nonzero_L0part = 0
    filtered_total_by_fixed = Counter()
    filtered_rank_by_fixed = {local: Counter() for local in range(len(fixed_idx))}

    for orb in free_orbits:
        X = pts[orb]
        xrank = c.gf2_rank(X)
        sig = np.bitwise_xor.reduce(X, axis=0).astype(np.uint8)
        if not np.array_equal(sig, (sigma @ X[0]) & 1):
            raise AssertionError("orbit-sum/sigma mismatch")
        sc = c.fixed_coord(sig, fix_pivots)
        in_L0 = sc in L0_coords
        if in_L0 and sc != 0:
            orbit_sum_in_L0_nonzero += 1
        matching_fixed = []
        for pc, local in fixed_coord_map.items():
            l0part = sc ^ pc
            if l0part in L0_coords:
                matching_fixed.append((local, l0part))
                filtered_total_by_fixed[local] += 1
                filtered_rank_by_fixed[local][(xrank, "sigma_eq_p" if l0part == 0 else "sigma_eq_p_plus_nonzero_L0")] += 1
                if l0part != 0:
                    filtered_nonzero_L0part += 1
        tag = "L0" if in_L0 else ("p_plus_L0" if matching_fixed else "other")
        orbit_profile[(xrank, tag, int(sc == 0), int(sc in fixed_coord_map), len(matching_fixed))] += 1

    type31_hist = Counter()
    per_fixed = []
    for local in range(len(fixed_idx)):
        fc = filtered_rank_by_fixed[local]
        rec = {
            "fixed_local": local,
            "fixed_global": int(fixed_idx[local]),
            "filtered_orbits_total": int(sum(fc.values())),
            "rank7_sigma_equals_p": int(fc.get((7, "sigma_eq_p"), 0)),
            "rank7_sigma_equals_p_plus_nonzero_L0": int(fc.get((7, "sigma_eq_p_plus_nonzero_L0"), 0)),
            "lower_rank_sigma_equals_p": int(sum(v for (xr, tag), v in fc.items() if xr < 7 and tag == "sigma_eq_p")),
            "lower_rank_sigma_equals_p_plus_nonzero_L0": int(sum(v for (xr, tag), v in fc.items() if xr < 7 and tag == "sigma_eq_p_plus_nonzero_L0")),
        }
        per_fixed.append(rec)
        type31_hist[(rec["filtered_orbits_total"], rec["rank7_sigma_equals_p"], rec["rank7_sigma_equals_p_plus_nonzero_L0"], rec["lower_rank_sigma_equals_p"], rec["lower_rank_sigma_equals_p_plus_nonzero_L0"])] += 1

    all_filtered_orbits_have_sigma_in_span_p = (filtered_nonzero_L0part == 0)
    all_orbits_with_sigma_in_L0_have_sigma_zero = (orbit_sum_in_L0_nonzero == 0)

    skeletons = []
    # r<=20: m>=3 from the fixed-part budget but 3 free 7-orbits already cost 21 terms.
    skeletons.append({
        "rank_range": "r<=20",
        "excluded": True,
        "reason": "For any invariant generated span containing L, P+L0 <= sigma(S) and dim sigma(S)<=dim(P)+m force m>=dim(L0)=3 free seven-orbits; this already uses 21 terms.",
    })
    skeletons.append({
        "rank": 21,
        "skeleton": "three free seven-orbits and no fixed point",
        "excluded": bool(all_orbits_with_sigma_in_L0_have_sigma_zero),
        "reason": "The fixed-part budget forces sigma(S)=L0, hence each of the three orbit sums must lie in L0. Enumeration shows every free orbit whose sum lies in L0 has sum 0, so three such sums cannot span L0.",
    })
    skeletons.append({
        "rank": 22,
        "skeleton": "three free seven-orbits and one fixed point p",
        "excluded": bool(all_filtered_orbits_have_sigma_in_span_p and fixed_L0_intersection == 0 and L0_dim == 3),
        "reason": "The fixed-part budget is tight: sigma(S) must equal <p>+L0, so every free orbit sum must lie in <p>+L0. Enumeration over all 49 fixed p shows every such orbit sum is exactly p (no nonzero L0 component), so sigma(S)=<p> cannot contain L0.",
    })

    conjugacy = gl3_order7_conjugacy(F7)

    conclusion_ok = all(s["excluded"] for s in skeletons)
    results = {
        "purpose": "Strengthened certificate excluding termwise diagonal order-7 sandwich symmetric rank<=22 UV-span representations over F2.",
        "field": "F2",
        "selected_F7_matrix": F7.astype(int).tolist(),
        "action_convention": {
            "U_and_V": "row-major covector action vec(F^T X F^{-T}) = kron(F^T,F^{-1}) vec_row(X)",
            "W_slice_coefficients": "row-major action vec(F^{-1} X F) = kron(F^{-1},F^T) vec_row(X); this is the inverse-transpose action paired with UV",
            **action_checks,
        },
        "fixed_spaces": {
            "FixE_dim": int(fixE_dim),
            "FixE_mod_L_dim": int(fixQ_dim),
            "L0_dim": int(L0_dim),
            "L0_equals_L_intersection_FixE": bool(L0_equals_intersection),
            "sigma_projector": sigma_checks,
        },
        "rank_one_orbits": {
            "rank_one_total": int(len(pts)),
            "fixed_count": int(len(fixed_idx)),
            "free_orbit_count": int(len(free_orbits)),
            "total_check": int(len(fixed_idx) + 7 * len(free_orbits)),
            "fixed_rank_one_coordinates_unique": bool(fixed_coords_unique),
            "fixed_rank_one_span_rank": int(fixed_span_rank),
            "fixed_rank_one_span_intersection_L": int(fixed_L_intersection),
            "fixed_rank_one_span_intersection_L0": int(fixed_L0_intersection),
            "free_orbit_profile": {str(k): int(v) for k, v in sorted(orbit_profile.items())},
        },
        "fixed_projection_enumeration": {
            "orbits_with_sigma_in_L0_but_nonzero": int(orbit_sum_in_L0_nonzero),
            "all_orbits_with_sigma_in_L0_have_sigma_zero": bool(all_orbits_with_sigma_in_L0_have_sigma_zero),
            "filtered_orbits_with_nonzero_L0part_over_all_fixed_p": int(filtered_nonzero_L0part),
            "every_filtered_orbit_has_sigma_in_span_p": bool(all_filtered_orbits_have_sigma_in_span_p),
            "histogram_over_49_fixed_points": {str(k): int(v) for k, v in sorted(type31_hist.items())},
            "per_fixed": per_fixed,
        },
        "skeleton_arguments": skeletons,
        "order7_diagonal_subgroup_conjugacy_in_GL3F2": conjugacy,
        "theorem_status": "proved_no_termwise_diagonal_order7_sandwich_symmetric_rank_le_22_over_F2" if conclusion_ok else "not_excluded_by_this_certificate",
        "scope": [
            "This is a named-family result, not a global lower bound for R_F2(T333): it treats representations whose individual rank-one UV terms are permuted by a diagonal order-7 sandwich subgroup.",
            "It does not exclude an invariant 22-dimensional UV subspace whose selected rank-one generators are not themselves a union of group orbits.",
            "It does not transfer to characteristic zero without a separate algebraic argument.",
            "The selected F7 result covers all diagonal order-7 sandwich subgroups over F2 by the recorded GL3(F2) conjugacy computation, not arbitrary non-diagonal De Groote triples.",
        ],
        "supersedes": [
            "data/symmetry_search/orbit_search_results.json: non-preserving action convention and random sampling only",
            "data/order7_exhaustive/order7_family_certificate.json: correct core computation but weaker/full-UV-rank packaging",
        ],
        "elapsed_sec": time.time() - t0,
    }

    out = out_dir / "order7_family_certificate_v2.json"
    out.write_text(json.dumps(results, indent=2) + "\n")
    print(json.dumps({
        "theorem_status": results["theorem_status"],
        "fixed_spaces": results["fixed_spaces"],
        "rank_one_orbits": {k: v for k, v in results["rank_one_orbits"].items() if k != "free_orbit_profile"},
        "free_orbit_profile": results["rank_one_orbits"]["free_orbit_profile"],
        "fixed_projection_enumeration_summary": {k: v for k, v in results["fixed_projection_enumeration"].items() if k != "per_fixed"},
        "skeleton_arguments": skeletons,
        "conjugacy": conjugacy,
        "out": str(out),
        "elapsed_sec": results["elapsed_sec"],
    }, indent=2))


if __name__ == "__main__":
    main()
