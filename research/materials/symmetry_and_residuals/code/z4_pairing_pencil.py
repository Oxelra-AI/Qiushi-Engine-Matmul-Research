# Blocks of invariant monomials.
def label_of_var(i):
    if i < dims['p']:
        return 'p'
    if i < dims['p'] + dims['q']:
        return 'q'
    if i < dims['p'] + dims['q'] + dims['z']:
        return 'z'
    return 'w'

def exp_of_var(i):
    return exponents[i]

def block_name(m):
    counts={"p":0,"q":0,"z":0,"w":0}
    e=0
    for i in m:
        counts[label_of_var(i)] += 1
        e = (e + exp_of_var(i)) % 4
    if e != 0:
        return None
    if counts == {"p":3,"q":0,"z":0,"w":0}: return "p3"
    if counts == {"p":1,"q":2,"z":0,"w":0}: return "pq2"
    if counts == {"p":1,"q":0,"z":1,"w":1}: return "pzw"
    if counts == {"p":0,"q":1,"z":2,"w":0}: return "qz2"
    if counts == {"p":0,"q":1,"z":0,"w":2}: return "qw2"
    return "other_invariant"

