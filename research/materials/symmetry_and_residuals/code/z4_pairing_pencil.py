# Conic intersection in the rowspace of a 2x3 matrix. Work projectively over F_p.
def conic_points_in_rowspace(M):
    r0=[int(M[0,j])%P for j in range(3)]
    r1=[int(M[1,j])%P for j in range(3)]
    points=[]
    # projective beta=1 affine chart: v=t*r0+r1. Also beta=0 point r0.
    def F(v):
        return (int(v[1])*int(v[1]) - 4*int(v[0])*int(v[2])) % P
    for t in range(P):
        v=[(t*r0[j]+r1[j])%P for j in range(3)]
        if v != [0,0,0] and F(v)==0:
            # normalize projectively by first nonzero entry
            for x in v:
                if x%P:
                    inv=pow(x,-1,P); break
            vn=tuple((x*inv)%P for x in v)
            if vn not in points: points.append(vn)
            if len(points) > 4:
                break
    v=r0
    if v != [0,0,0] and F(v)==0:
        for x in v:
            if x%P:
                inv=pow(x,-1,P); break
        vn=tuple((x*inv)%P for x in v)
        if vn not in points: points.append(vn)
    return points

