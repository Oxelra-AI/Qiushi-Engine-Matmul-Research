#!/usr/bin/env python3
"""
analysis: repair the Z4 pairing convention and validate the eigenblock pencil-conic instrument.

This script treats BILR's residual cubic C(M)=sum_{11 cubes} <L_i,M>^3
with the actual packed Euclidean pairing <L,M>=tr(L^T M).  The coefficient
cube orbit is generated by L -> a0 L a0^{-1}; therefore the variable action
preserving the residual is M -> a0^T M a0^{-T}.  We do not assume this: first
we brute-force test four natural conjugation actions on all 165 cubic coefficients.

After selecting the coefficientwise preserving action, the script builds its
eigen-coordinates over F_p (p=65521, i^2=-1), checks the invariant block split
p^3(10)+pq^2(9)+pzw(12)+qz^2(6)+qw^2(6)=43, verifies that the BILR residual has
zero coefficients outside these blocks, and runs the qz^2 pencil-conic positive
control.  The conic intersection is compared projectively with the two size-4
BILR cube-orbit z-lines; no averaging is used except as a check that Proj_inv(C)=C.
"""
from __future__ import annotations

import itertools, json
from pathlib import Path
import numpy as np

