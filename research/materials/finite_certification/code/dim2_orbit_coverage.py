#!/usr/bin/env python3
"""Independent exhaustive classification of 2D A-subspaces under MM A-actions.

Purpose: close the proof gap that all 2D subspaces whose three nonzero 3x3
matrices have rank >=2 are covered by Wang orbit indices 484--491.

This script does not use the Wang orbit cache to form orbits.  It enumerates all
{9 choose 2}_2 = 43435 two-dimensional subspaces of F2^9, represents each by its
three nonzero elements, and computes orbit closure under generators of
  A -> P^T A Q^{-T}  (P,Q in GL_3(F2))
and A -> A^T.  The GL_3 factors are generated by elementary transvections.
Only after the independent orbits are computed does the script compare Wang's
cached representative basis/cert_index to the computed orbit identifiers.
"""
from __future__ import annotations

import argparse
import json
import pickle
import time
from collections import Counter, defaultdict, deque
from pathlib import Path
from typing import Iterable, Sequence, Tuple

CACHE_PATH = Path("data/wang_f2_lb20/wang_orbit_closed_cache.pkl")
OUT = Path("data/orbit_coverage/dim2_orbit_coverage.json")


def bits_to_mat(x: int):
    return [[(int(x) >> (3*i+j)) & 1 for j in range(3)] for i in range(3)]


def mat_to_bits(M) -> int:
    out = 0
    for i in range(3):
        for j in range(3):
            if int(M[i][j]) & 1:
                out |= 1 << (3*i+j)
    return out


def mat_mul(A, B):
    return [[sum(int(A[i][k]) & int(B[k][j]) for k in range(3)) & 1 for j in range(3)] for i in range(3)]


def mat_transpose(A):
    return [[A[j][i] for j in range(3)] for i in range(3)]


def mat_identity():
    return [[1 if i==j else 0 for j in range(3)] for i in range(3)]


def gf2_rank_mat(M) -> int:
    rows = []
    for i in range(3):
        r = 0
        for j in range(3):
            if int(M[i][j]) & 1:
                r |= 1 << j
        rows.append(r)
    basis = []
    for v0 in rows:
        v = v0
        for b in basis:
            p = b.bit_length()-1
            if p >= 0 and ((v>>p)&1):
                v ^= b
        if v:
            p = v.bit_length()-1
            for ii,b in enumerate(basis):
                if (b>>p)&1:
                    basis[ii] = b ^ v
            basis.append(v); basis.sort(reverse=True)
    return len(basis)


def gf2_rank_bits(x: int) -> int:
    return gf2_rank_mat(bits_to_mat(x))


def gf2_inv(M):
    # Gauss-Jordan over F2 on row-bit representation.
    left = []
    right = []
    for i in range(3):
        l = 0; r = 0
        for j in range(3):
            if M[i][j] & 1: l |= 1 << j
            if i == j: r |= 1 << j
        left.append(l); right.append(r)
    row = 0
    for col in range(3):
        piv = None
        for i in range(row,3):
            if (left[i] >> col) & 1:
                piv = i; break
        if piv is None:
            raise ValueError('singular')
        if piv != row:
            left[row], left[piv] = left[piv], left[row]
            right[row], right[piv] = right[piv], right[row]
        for i in range(3):
            if i != row and ((left[i] >> col) & 1):
                left[i] ^= left[row]
                right[i] ^= right[row]
        row += 1
    Minv = [[(right[i] >> j) & 1 for j in range(3)] for i in range(3)]
    return Minv


def elem_transvection(i: int, j: int):
    M = mat_identity()
    M[i][j] ^= 1
    return M


def transform_A(a: int, P=None, Q=None, transpose: bool=False) -> int:
    A = bits_to_mat(a)
    if transpose:
        return mat_to_bits(mat_transpose(A))
    if P is None: P = mat_identity()
    if Q is None: Q = mat_identity()
    Qinv = gf2_inv(Q)
    A2 = mat_mul(mat_transpose(P), mat_mul(A, mat_transpose(Qinv)))
    return mat_to_bits(A2)


def all_2d_subspaces() -> list[Tuple[int,int,int]]:
    seen = set()
    out = []
    for a in range(1,512):
        for b in range(a+1,512):
            c = a ^ b
            if c == 0: continue
            tri = tuple(sorted((a,b,c)))
            if tri not in seen:
                seen.add(tri); out.append(tri)
    out.sort()
    return out


def transform_space(tri: Tuple[int,int,int], gen) -> Tuple[int,int,int]:
    kind, mat = gen
    if kind == 'left':
        vals = [transform_A(x, P=mat) for x in tri]
    elif kind == 'right':
        vals = [transform_A(x, Q=mat) for x in tri]
    elif kind == 'transpose':
        vals = [transform_A(x, transpose=True) for x in tri]
    else:
        raise ValueError(kind)
    return tuple(sorted(vals))


def span_nonzero_from_basis(basis: Sequence[int]) -> Tuple[int,int,int]:
    vals = set()
    for c in range(1, 1 << len(basis)):
        v = 0
        for i,b in enumerate(basis):
            if (c>>i)&1: v ^= int(b)
        vals.add(v)
    assert len(vals) == 3
    return tuple(sorted(vals))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', type=Path, default=OUT)
    args = ap.parse_args()
    t0 = time.time()
    gens = []
    for i in range(3):
        for j in range(3):
            if i != j:
                E = elem_transvection(i,j)
                gens.append(('left', E))
                gens.append(('right', E))
    gens.append(('transpose', None))

    spaces = all_2d_subspaces()
    allset = set(spaces)
    unvisited = set(spaces)
    orbit_id = {}
    orbit_records = []
    while unvisited:
        seed = min(unvisited)
        q = deque([seed]); unvisited.remove(seed)
        members = []
        while q:
            tri = q.popleft(); members.append(tri)
            for gen in gens:
                img = transform_space(tri, gen)
                if img not in allset:
                    raise AssertionError(f'image not a 2D subspace: {tri} -> {img}')
                if img in unvisited:
                    unvisited.remove(img); q.append(img)
        oid = len(orbit_records)
        for m in members: orbit_id[m] = oid
        rank_hist = Counter(tuple(sorted(gf2_rank_bits(x) for x in m)) for m in members)
        all_high_count = sum(1 for m in members if min(gf2_rank_bits(x) for x in m) >= 2)
        orbit_records.append({
            'computed_orbit_id': oid,
            'size': len(members),
            'canonical_nonzero_triple': list(min(members)),
            'rank_pattern_hist': {str(k): int(v) for k,v in rank_hist.items()},
            'all_high_member_count': all_high_count,
        })
    # Compare Wang cache representatives after independent orbiting.
    with CACHE_PATH.open('rb') as f:
        cache = pickle.load(f)
    dim2_reps = [o for o in cache['orbits'] if int(o['dim']) == 2]
    wang_map = []
    by_orbit = defaultdict(list)
    for o in dim2_reps:
        tri = span_nonzero_from_basis([int(x) for x in o['basis']])
        oid = orbit_id[tri]
        ranks = sorted(gf2_rank_bits(x) for x in tri)
        rec = {
            'cert_index': int(o['cert_index']),
            'basis': [int(x) for x in o['basis']],
            'triple': list(tri),
            'computed_orbit_id': oid,
            'rank_pattern': ranks,
            'raw_lb': int(o['raw_lb']),
            'cache_orbit_size': int(o.get('orbit_size', -1)),
            'computed_orbit_size': orbit_records[oid]['size'],
            'proof_type': o.get('proof_type'),
        }
        wang_map.append(rec); by_orbit[oid].append(rec)
    all_high_oids = sorted(i for i,r in enumerate(orbit_records) if r['all_high_member_count'] == r['size'])
    all_high_cert_indices = sorted(rec['cert_index'] for rec in wang_map if rec['computed_orbit_id'] in all_high_oids)
    # More directly classify every all-high member.
    all_high_members = [tri for tri in spaces if min(gf2_rank_bits(x) for x in tri) >= 2]
    all_high_member_oids = sorted(set(orbit_id[tri] for tri in all_high_members))
    all_high_member_cert_indices = sorted(rec['cert_index'] for rec in wang_map if rec['computed_orbit_id'] in all_high_member_oids)

    out = {
        'schema': 'dim2_orbit_coverage_v1',
        'group_generators': 'left/right elementary transvections for GL3xGL3 plus A transpose',
        'n_spaces': len(spaces),
        'expected_n_spaces': 43435,
        'n_computed_orbits': len(orbit_records),
        'generator_count': len(gens),
        'computed_orbits': orbit_records,
        'wang_dim2_representatives': sorted(wang_map, key=lambda r: r['cert_index']),
        'computed_orbit_to_wang_indices': {str(k): [r['cert_index'] for r in sorted(v, key=lambda x:x['cert_index'])] for k,v in by_orbit.items()},
        'wang_has_one_rep_per_computed_orbit': len(dim2_reps) == len(orbit_records) and all(len(v) == 1 for v in by_orbit.values()),
        'all_high_member_count': len(all_high_members),
        'all_high_computed_orbit_ids': all_high_member_oids,
        'all_high_cert_indices': all_high_member_cert_indices,
        'all_high_exact_484_491': all_high_member_cert_indices == list(range(484,492)),
        'all_high_orbit_sizes_sum': sum(orbit_records[i]['size'] for i in all_high_member_oids),
        'cache_orbit_sizes_match': all(r['cache_orbit_size'] == r['computed_orbit_size'] for r in wang_map),
        'elapsed_sec': time.time() - t0,
    }
    out['ok'] = (out['n_spaces'] == out['expected_n_spaces'] and out['n_computed_orbits'] == 14 and out['wang_has_one_rep_per_computed_orbit'] and out['all_high_exact_484_491'] and out['cache_orbit_sizes_match'])
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(out, indent=2, sort_keys=True) + '\n')
    print(json.dumps({
        'out': str(args.out),
        'ok': out['ok'],
        'n_spaces': out['n_spaces'],
        'n_orbits': out['n_computed_orbits'],
        'all_high_member_count': out['all_high_member_count'],
        'all_high_cert_indices': out['all_high_cert_indices'],
        'elapsed_sec': out['elapsed_sec'],
    }, indent=2, sort_keys=True))

if __name__ == '__main__':
    main()
