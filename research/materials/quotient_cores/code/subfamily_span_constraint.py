#!/usr/bin/env python3
"""analysis: compute the full subfamily span inequality on a verified rank-23 scheme.

For a decomposition P = sum_t M_t with rank(P)=27 and
sum_t rank(M_t)=27+e, every subfamily of column spaces has defect at most e:

    dim(sum_{t in S} col(M_t)) >= sum_{t in S} rank(M_t) - e.

For matrix multiplication in the A-split flattening,
col(M_t)=col(A_t) tensor <vec(B_t)>, rank(M_t)=rank(A_t), so for every subspace
V of the B-coordinate span generated by the observed B_t values,

    sum_{t: vec(B_t) in V} rank(A_t) <= 3 dim(V) + e_A.

The same is tested for the A-row/C side and for the two cyclic slot images.
This script is a consistency and leverage check on the known rank-23 control;
the proof of the inequality is the rank-additivity argument, not this finite run.
"""
from __future__ import annotations

import json
import os
from collections import defaultdict
from pathlib import Path
from typing import Iterable, List, Tuple

ROOT = Path(os.environ.get("QIUSHI_USER_ROOT", "."))
WS = ROOT / "research" / "research_record" / "workspace"
OUT = WS / "data" / "span_constraints"
OUT.mkdir(parents=True, exist_ok=True)
CTRL = WS / "data" / "pivot_fixed" / "pivot17_rank23_transformed_control.json"

N = 9


def int_to_rows(v: int) -> List[int]:
    return [sum(((v >> (3*i+j)) & 1) << j for j in range(3)) for i in range(3)]


def transpose_int(v: int) -> int:
    out = 0
    for i in range(3):
        for j in range(3):
            if (v >> (3*i+j)) & 1:
                out |= 1 << (3*j+i)
    return out


def f2_rank_matrix_int(v: int) -> int:
    rows = int_to_rows(v)
    r = 0
    for c in range(3):
        piv = None
        for rr in range(r, 3):
            if (rows[rr] >> c) & 1:
                piv = rr
                break
        if piv is None:
            continue
        rows[r], rows[piv] = rows[piv], rows[r]
        for rr in range(3):
            if rr != r and ((rows[rr] >> c) & 1):
                rows[rr] ^= rows[r]
        r += 1
    return r


def rref_key_from_vectors(vectors: Iterable[int], n: int = N) -> Tuple[int, ...]:
    """Canonical RREF basis as tuple of row bitmasks with increasing pivots."""
    basis = [0] * n  # basis[pivot] has leading bit pivot
    for x in vectors:
        x &= (1 << n) - 1
        while x:
            p = (x & -x).bit_length() - 1  # lowest set bit
            if basis[p]:
                x ^= basis[p]
            else:
                basis[p] = x
                # eliminate this pivot from all other rows for reduced form
                for q in range(n):
                    if q != p and basis[q] and ((basis[q] >> p) & 1):
                        basis[q] ^= x
                break
    return tuple(b for b in basis if b)


def add_vector_to_key(key: Tuple[int, ...], v: int) -> Tuple[int, ...]:
    return rref_key_from_vectors(list(key) + [v])


def dim_key(key: Tuple[int, ...]) -> int:
    return len(key)


def in_subspace(v: int, key: Tuple[int, ...]) -> bool:
    x = v
    # Key is reduced with leading lowest bit. Reduce using rows by pivot.
    piv_to_row = {}
    for b in key:
        p = (b & -b).bit_length() - 1
        piv_to_row[p] = b
    while x:
        p = (x & -x).bit_length() - 1
        row = piv_to_row.get(p)
        if row is None:
            return False
        x ^= row
    return True


def enumerate_join_closure(values: List[int]) -> List[Tuple[int, ...]]:
    """All distinct spans generated by subsets of the listed projective values."""
    closure = {tuple()}
    for v in sorted(set(values)):
        additions = {add_vector_to_key(key, v) for key in closure}
        closure |= additions
    return sorted(closure, key=lambda k: (len(k), k))


def analyze_orientation(name: str, vectors: List[int], weights: List[int], e: int, examples_limit: int = 12) -> dict:
    spaces = enumerate_join_closure(vectors)
    records = []
    min_margin = None
    max_defect = None
    tight = []
    negative = []
    hist_by_dim = defaultdict(lambda: {"count": 0, "min_margin": None, "max_defect": None})
    for key in spaces:
        dim = dim_key(key)
        idx = [i for i, v in enumerate(vectors) if in_subspace(v, key)]
        wsum = sum(weights[i] for i in idx)
        defect = wsum - 3 * dim
        margin = e - defect
        rec = {
            "basis": list(key),
            "dim": dim,
            "term_indices": idx,
            "weight_sum": wsum,
            "defect_weight_minus_3dim": defect,
            "margin_e_minus_defect": margin,
        }
        records.append(rec)
        if min_margin is None or margin < min_margin:
            min_margin = margin
        if max_defect is None or defect > max_defect:
            max_defect = defect
        h = hist_by_dim[dim]
        h["count"] += 1
        h["min_margin"] = margin if h["min_margin"] is None else min(h["min_margin"], margin)
        h["max_defect"] = defect if h["max_defect"] is None else max(h["max_defect"], defect)
        if margin == 0:
            tight.append(rec)
        if margin < 0:
            negative.append(rec)
    # Interesting: closest to tight, then small dimension, then high weight.
    near = sorted(records, key=lambda r: (r["margin_e_minus_defect"], r["dim"], -r["weight_sum"], r["basis"]))[:examples_limit]
    return {
        "name": name,
        "n_terms": len(vectors),
        "distinct_projective_values": len(set(vectors)),
        "observed_span_dim": dim_key(rref_key_from_vectors(vectors)),
        "subspaces_in_join_closure": len(spaces),
        "e": e,
        "ok": len(negative) == 0,
        "max_defect_weight_minus_3dim": max_defect,
        "min_margin_e_minus_defect": min_margin,
        "tight_count": len(tight),
        "negative_count": len(negative),
        "hist_by_dim": {str(k): v for k, v in sorted(hist_by_dim.items())},
        "tight_examples": tight[:examples_limit],
        "near_tight_examples": near,
        "negative_examples": negative[:examples_limit],
    }


def main() -> None:
    ctrl = json.loads(CTRL.read_text())
    terms = ctrl["terms"]
    A = [int(t[0]) for t in terms]
    B = [int(t[1]) for t in terms]
    C = [int(t[2]) for t in terms]
    rA = [f2_rank_matrix_int(x) for x in A]
    rB = [f2_rank_matrix_int(x) for x in B]
    rC = [f2_rank_matrix_int(x) for x in C]
    eA = sum(rA) - 27
    eB = sum(rB) - 27
    eC = sum(rC) - 27

    orientations = [
        analyze_orientation("A_split_columns_by_span_B", B, rA, eA),
        analyze_orientation("A_split_rows_by_span_C", C, rA, eA),
        analyze_orientation("B_split_columns_by_span_C_transpose", [transpose_int(x) for x in C], rB, eB),
        analyze_orientation("B_split_rows_by_span_A_transpose", [transpose_int(x) for x in A], rB, eB),
        analyze_orientation("C_split_columns_by_span_A", A, rC, eC),
        analyze_orientation("C_split_rows_by_span_B_transpose", [transpose_int(x) for x in B], rC, eC),
    ]

    result = {
        "schema": "research_record_subfamily_span_constraint_v1",
        "rank23_scheme_source": str(CTRL),
        "n_terms": len(terms),
        "slot_rank_sums": {"A": sum(rA), "B": sum(rB), "C": sum(rC)},
        "slot_excesses": {"e_A": eA, "e_B": eB, "e_C": eC},
        "theorem": {
            "field_independent": "If P=sum_t M_t has rank r and sum_t rank(M_t)=r+e, then every subfamily S has dim(sum_{t in S} col(M_t)) >= sum_{t in S} rank(M_t)-e, and similarly for row spaces.",
            "matmul_A_split": "For M_t=A_t tensor(vec(B_t) vec(C_t)^T), rank(M_t)=rank(A_t), col(M_t)=col(A_t) tensor <vec(B_t)>, row(M_t)=row(A_t) tensor <vec(C_t)>. Hence for every B-subspace V, sum_{vec(B_t) in V} rank(A_t) <= 3 dim(V)+e_A, and dually for C.",
            "interpretation": "The recorded computation enumerates all spans generated by observed rank-23 slot values; it is a consistency/leverage check, not the proof of the inequality. The proof is the global relation-space injection into the e-dimensional kernel.",
        },
        "orientation_results": orientations,
        "all_orientations_ok": all(o["ok"] for o in orientations),
        "any_negative_margin": any(o["negative_count"] for o in orientations),
        "summary_table": [
            {
                "name": o["name"],
                "e": o["e"],
                "distinct_values": o["distinct_projective_values"],
                "observed_span_dim": o["observed_span_dim"],
                "join_closure_subspaces": o["subspaces_in_join_closure"],
                "max_defect": o["max_defect_weight_minus_3dim"],
                "min_margin": o["min_margin_e_minus_defect"],
                "tight_count": o["tight_count"],
                "ok": o["ok"],
            }
            for o in orientations
        ],
        "comparison_with_contraction": "For codimension-one V=ker(phi) the complementary contraction bound counts terms with phi(value)!=0 and is often stronger in unweighted term count; the subfamily span inequality is rank-weighted and most useful on small V or fixed-A completions. They are complementary finite filters.",
    }
    out = OUT / "subfamily_span_constraint_rank23.json"
    out.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps({
        "ok": result["all_orientations_ok"],
        "out": str(out),
        "summary_table": result["summary_table"],
    }, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
