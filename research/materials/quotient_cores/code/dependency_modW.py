#!/usr/bin/env python3
"""analysis: dependency map of rank-one points modulo W=col(D).

Exact organization.  Let U contain W and let S(U) be the rank-one 9x9
matrices contained in U.  Projection modulo W is injective on nonzero rank-one
matrices.  For rank-one points s_i in S(U), write their coordinates in U as
q_i + w_i with q_i in a fixed complement of W and w_i in W.  Any dependency
among the q_i lifts to sum w_i in W.  The image of this dependency map is
span(S(U)) cap W.  Thus U is generated by its rank-one points exactly when the
q_i span U/W and these lifted dependency values span all of W.

This script measures which dependencies actually supply W in verified rank-23
controls and in the best W-containing hyperplanes from analysis.  It compares
three-term projected dependencies with the full dependency space; three-term
relations are useful evidence but are not assumed to generate all completion
relations.
"""
from __future__ import annotations

import argparse
import itertools
import json
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path
from typing import Dict, Iterable, List, Sequence, Tuple

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import residual_repair_geometry as rg  # type: ignore
from rankone_lattice import (  # type: ignore
    echelon_add,
    echelon_reduce,
    independent_subset,
    kernel_basis,
    rank_of_int_list,
    rank_ones_in_span,
    span_masks,
)

OUTDIR = Path("data/dependency_modW")


def popcnt(x: int) -> int:
    return int(x).bit_count()


def mat9_rank_f2(v: int) -> int:
    rows = [(int(v) >> (9 * i)) & 0x1FF for i in range(9)]
    piv: Dict[int, int] = {}
    r = 0
    for row in rows:
        x = row
        while x:
            p = x.bit_length() - 1
            if p in piv:
                x ^= piv[p]
            else:
                piv[p] = x
                r += 1
                break
    return r


def bitparity(x: int) -> int:
    return popcnt(x) & 1


def build_coord_basis(terms: Sequence[Tuple[int, int, int]]) -> Dict[int, Tuple[int, int]]:
    basis: Dict[int, Tuple[int, int]] = {}
    for i, (a, b, _c) in enumerate(terms):
        ok = echelon_add(basis, rg.vec_mask9_to_outer81(a, b), 1 << i)
        if not ok:
            raise RuntimeError(f"decomposition columns dependent at term {i}")
    return basis


def W_coords_in_U(Ubasis: Dict[int, Tuple[int, int]], W_cols: Sequence[int]) -> List[int]:
    coords = []
    for w in W_cols:
        rem, tag = echelon_reduce(Ubasis, w)
        if rem != 0:
            raise RuntimeError("W is not contained in this U")
        coords.append(int(tag))
    if rank_of_int_list(coords) != 9:
        raise RuntimeError("W coordinate rank is not 9")
    return coords


def make_Wcoord_basis(Wcoords: Sequence[int]) -> Dict[int, Tuple[int, int]]:
    basis: Dict[int, Tuple[int, int]] = {}
    for j, wc in enumerate(Wcoords):
        ok = echelon_add(basis, int(wc), 1 << j)
        if not ok:
            raise RuntimeError("dependent W coordinate basis")
    return basis


def quotient_decomposition(tags: Sequence[int], Wbasis: Dict[int, Tuple[int, int]]) -> Tuple[List[int], List[int]]:
    qtags: List[int] = []
    wtags: List[int] = []
    for t in tags:
        rem, wt = echelon_reduce(Wbasis, int(t))
        qtags.append(int(rem))
        wtags.append(int(wt))
    return qtags, wtags


def wtag_to_ambient(wtag: int, W_cols: Sequence[int]) -> int:
    v = 0
    for j, w in enumerate(W_cols):
        if (int(wtag) >> j) & 1:
            v ^= int(w)
    return v


def dependency_summary(qtags: Sequence[int], wtags: Sequence[int], W_cols: Sequence[int], max_enum_kernel_dim: int = 22) -> dict:
    qrank = rank_of_int_list(qtags)
    kbasis = kernel_basis(qtags)
    kdim = len(kbasis)
    out = {
        "q_rank": int(qrank),
        "projected_dependency_dim": int(kdim),
        "dependency_enum_truncated": False,
    }
    if kdim > max_enum_kernel_dim:
        out["dependency_enum_truncated"] = True
        return out

    support_hist: Counter[int] = Counter()
    w_rank_hist: Counter[int] = Counter()
    cutoff_wtags: Dict[int, List[int]] = defaultdict(list)
    full_wtags: List[int] = []
    zero_w_support_hist: Counter[int] = Counter()
    nonzero_examples = []
    zero_examples = []
    all_dep_count = 0
    for dep in span_masks(kbasis):
        all_dep_count += 1
        supp = popcnt(dep)
        wtag = 0
        for i, wt in enumerate(wtags):
            if (dep >> i) & 1:
                wtag ^= int(wt)
        support_hist[supp] += 1
        full_wtags.append(wtag)
        wr = 0 if wtag == 0 else mat9_rank_f2(wtag_to_ambient(wtag, W_cols))
        w_rank_hist[wr] += 1
        cutoff_wtags[supp].append(wtag)
        if wtag == 0:
            zero_w_support_hist[supp] += 1
            if len(zero_examples) < 12 and supp <= 5:
                zero_examples.append(int(dep))
        elif len(nonzero_examples) < 12 and supp <= 6:
            nonzero_examples.append({"dep_mask": int(dep), "support": int(supp), "wtag": int(wtag), "W_matrix_rank": int(wr)})

    full_w_dim = rank_of_int_list(full_wtags)
    cutoff_rows = []
    accum: List[int] = []
    for c in range(1, max(support_hist.keys(), default=0) + 1):
        accum.extend(cutoff_wtags.get(c, []))
        cutoff_rows.append({
            "support_at_most": c,
            "relation_count_at_most": int(sum(v for k, v in support_hist.items() if k <= c)),
            "W_image_dim": int(rank_of_int_list(accum)),
        })
    out.update({
        "dependency_count": int(all_dep_count),
        "W_image_dim_full_dependency_space": int(full_w_dim),
        "dependency_support_hist": {str(k): int(v) for k, v in sorted(support_hist.items())},
        "lifted_W_matrix_rank_hist": {str(k): int(v) for k, v in sorted(w_rank_hist.items())},
        "zero_W_relation_support_hist": {str(k): int(v) for k, v in sorted(zero_w_support_hist.items())},
        "W_image_dim_by_support_cutoff": cutoff_rows,
        "small_nonzero_lift_examples": nonzero_examples,
        "small_zero_lift_examples": zero_examples,
    })
    return out


def analyze_rankone_family(label: str, U_dim: int, rankones: Sequence[Tuple[int, int, int]], Wcoords: Sequence[int], W_cols: Sequence[int], extra: dict | None = None) -> dict:
    tags = [int(t) for _a, _b, t in rankones]
    Wbasis = make_Wcoord_basis(Wcoords)
    qtags, wtags = quotient_decomposition(tags, Wbasis)
    span_rank = rank_of_int_list(tags)
    qrank = rank_of_int_list(qtags)
    dep = dependency_summary(qtags, wtags, W_cols)
    out = {
        "label": label,
        "U_dim": int(U_dim),
        "rank_one_count": int(len(rankones)),
        "rank_one_span_rank_in_U": int(span_rank),
        "quotient_target_dim": int(U_dim - 9),
        "projected_rank_one_span_dim": int(qrank),
        "rank_one_span_intersection_W_dim": int(span_rank - qrank),
        "rank_one_generates_U": bool(span_rank == U_dim),
        "projects_onto_U_mod_W": bool(qrank == U_dim - 9),
        "W_supplied_by_dependencies": bool((span_rank - qrank) == 9),
        "dependency_summary": dep,
    }
    if extra:
        out.update(extra)
    return out


def functional_space(Wcoords: Sequence[int], nbits: int) -> List[int]:
    # All linear functionals phi on U annihilating W, represented as n-bit masks.
    rows = [int(w) for w in Wcoords]
    piv: Dict[int, int] = {}
    for r in rows:
        x = r
        while x:
            p = x.bit_length() - 1
            if p in piv:
                x ^= piv[p]
            else:
                piv[p] = x
                break
    pivots = sorted(piv.keys())
    free = [i for i in range(nbits) if i not in piv]
    basis = []
    for f in free:
        phi = 1 << f
        for p in pivots:
            row = piv[p]
            if bitparity(row & phi):
                phi ^= 1 << p
        basis.append(phi)
    for phi in basis:
        for w in Wcoords:
            if bitparity(phi & int(w)):
                raise RuntimeError("functional does not annihilate W")
    return basis


def analyze_best_hyperplanes(S: Sequence[Tuple[int, int, int]], Wcoords: Sequence[int], W_cols: Sequence[int], nbits: int, max_records: int = 8) -> dict:
    phibasis = functional_space(Wcoords, nbits)
    best_rank = -1
    best_records = []
    hist = Counter()
    for phi in span_masks(phibasis):
        kept = [(a, b, t) for a, b, t in S if bitparity(phi & int(t)) == 0]
        r = rank_of_int_list([t for _a, _b, t in kept])
        hist[r] += 1
        if r > best_rank:
            best_rank = r
            best_records = [(phi, kept)]
        elif r == best_rank and len(best_records) < max_records:
            best_records.append((phi, kept))
    analyzed = []
    for phi, kept in best_records[:max_records]:
        analyzed.append(analyze_rankone_family(
            f"best_hyperplane_phi_{phi}",
            22,
            kept,
            Wcoords,
            W_cols,
            {"phi": int(phi), "rank_one_count_in_hyperplane": int(len(kept))},
        ))
    return {
        "functional_space_dim": int(len(phibasis)),
        "hyperplanes_tested": int((1 << len(phibasis)) - 1),
        "rank_one_span_rank_hist_over_hyperplanes": {str(k): int(v) for k, v in sorted(hist.items())},
        "best_rank_one_span_rank": int(best_rank),
        "best_records_analyzed": analyzed,
    }


def analyze_dim20_21_by_subsets(S: Sequence[Tuple[int, int, int]], Wcoords: Sequence[int], dims: Sequence[int], time_limit_sec: float = 120.0) -> dict:
    # Complete for small S (<=26 at d=20/21); for cn122 d=20 is 10M subsets and
    # still normally finishes quickly with bit ranks.  If it reaches the time
    # limit it records progress rather than returning a mathematical exclusion.
    tags = [int(t) for _a, _b, t in S]
    out = {}
    start_all = time.time()
    for d in dims:
        t0 = time.time()
        tested = 0
        rank_d = 0
        containsW = 0
        witness = None
        complete = True
        for comb in itertools.combinations(range(len(tags)), d):
            tested += 1
            sub = [tags[i] for i in comb]
            if rank_of_int_list(sub) != d:
                continue
            rank_d += 1
            if rank_of_int_list(sub + list(Wcoords)) == d:
                containsW += 1
                witness = list(comb)
                break
            if time.time() - t0 > time_limit_sec:
                complete = False
                break
        out[str(d)] = {
            "tested_subsets": int(tested),
            "complete_without_witness": bool(complete and witness is None),
            "stopped_after_witness": bool(witness is not None),
            "rank_d_subsets_seen": int(rank_d),
            "subsets_spanning_W_seen": int(containsW),
            "witness_indices": witness,
            "elapsed_sec": time.time() - t0,
        }
        # If already found smaller decomposition inside known span, no need to
        # enumerate more dimensions.
        if witness is not None:
            break
    out["total_elapsed_sec"] = time.time() - start_all
    return out


def analyze_source(name: str, terms: Sequence[Tuple[int, int, int]], W_cols: Sequence[int], subset_time_limit: float) -> dict:
    Ubasis = build_coord_basis(terms)
    Wcoords = W_coords_in_U(Ubasis, W_cols)
    nbits = len(terms)
    S_all = rank_ones_in_span(Ubasis)
    S_orig = [(int(a), int(b), 1 << i) for i, (a, b, _c) in enumerate(terms)]

    res = {
        "source": name,
        "U_dim": int(len(Ubasis)),
        "W_coord_rank": int(rank_of_int_list(Wcoords)),
        "rank_one_count_all": int(len(S_all)),
        "original_term_analysis": analyze_rankone_family("original_23_terms", len(Ubasis), S_orig, Wcoords, W_cols),
        "all_rank_one_points_analysis": analyze_rankone_family("all_rank_one_points_in_U", len(Ubasis), S_all, Wcoords, W_cols),
        "best_hyperplanes": analyze_best_hyperplanes(S_all, Wcoords, W_cols, nbits),
        "dim20_21_rank_one_generated_search_in_this_span": analyze_dim20_21_by_subsets(S_all, Wcoords, [20, 21], subset_time_limit),
    }
    return res


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sources", default="cn122_qmm,flip_rank23_text,pivot17_transformed_rank23")
    ap.add_argument("--subset-time-limit", type=float, default=180.0)
    ap.add_argument("--outdir", type=Path, default=OUTDIR)
    args = ap.parse_args()
    args.outdir.mkdir(parents=True, exist_ok=True)
    sources = rg.load_sources()
    W_cols = rg.D_columns_as_ints()
    out = {
        "schema": "s0908_dependency_modW_v1",
        "meaning": "Dependency-map analysis of rank-one points modulo W=col(D); compares three-term projected dependencies with the full dependency image in W and searches for rank-one generated dim20/21 subspaces inside known rank23 spans.",
        "results": {},
    }
    t0 = time.time()
    for name in [x.strip() for x in args.sources.split(",") if x.strip()]:
        print(f"=== {name} ===", flush=True)
        r = analyze_source(name, sources[name], W_cols, args.subset_time_limit)
        out["results"][name] = r
        compact = {
            "rank_one_count_all": r["rank_one_count_all"],
            "orig_dep_W_dim": r["original_term_analysis"]["dependency_summary"].get("W_image_dim_full_dependency_space"),
            "orig_W_dim_support3": next((row["W_image_dim"] for row in r["original_term_analysis"]["dependency_summary"].get("W_image_dim_by_support_cutoff", []) if row["support_at_most"] == 3), None),
            "all_dep_W_dim": r["all_rank_one_points_analysis"]["dependency_summary"].get("W_image_dim_full_dependency_space"),
            "all_W_dim_support3": next((row["W_image_dim"] for row in r["all_rank_one_points_analysis"]["dependency_summary"].get("W_image_dim_by_support_cutoff", []) if row["support_at_most"] == 3), None),
            "best_hyperplane_rank": r["best_hyperplanes"]["best_rank_one_span_rank"],
            "dim20_21": r["dim20_21_rank_one_generated_search_in_this_span"],
        }
        print(json.dumps(compact, indent=2, sort_keys=True), flush=True)
    out["elapsed_sec"] = time.time() - t0
    op = args.outdir / "dependency_modW.json"
    op.write_text(json.dumps(out, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"status": "ok", "out": str(op), "elapsed_sec": out["elapsed_sec"]}, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
