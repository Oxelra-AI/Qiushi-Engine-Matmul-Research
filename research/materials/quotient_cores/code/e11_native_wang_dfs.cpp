struct Searcher {
    const std::vector<Constraint>& rows;
    const std::vector<std::vector<uint32_t>>& point_rows;
    int target_depth;
    double time_limit;
    std::chrono::steady_clock::time_point start;
    BranchResult res;
    std::vector<uint8_t> counts;
    std::vector<int> chosen;
    uint64_t allowed_words[4];
    int max_solutions_store;

    Searcher(const std::vector<Constraint>& rows_, const std::vector<std::vector<uint32_t>>& pr_,
             int target_depth_, double time_limit_, int max_store=5)
        : rows(rows_), point_rows(pr_), target_depth(target_depth_), time_limit(time_limit_),
          counts(rows_.size(), 0), max_solutions_store(max_store) {
        allowed_words[0]=allowed_words[1]=allowed_words[2]=allowed_words[3]=~0ULL;
        allowed_words[0] &= ~1ULL; // point 0 unused
        // Points only 1..255; all four words okay after clearing 0.
    }

    bool timed_out() const {
        if (time_limit <= 0) return false;
        double t = std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
        return t >= time_limit;
    }

    bool allowed(int q) const { return getbit4(allowed_words, q); }

    bool add_point(int q, std::vector<uint32_t>& touched) {
        touched.clear();
        for (uint32_t ri: point_rows[q]) {
            uint8_t nv = counts[ri] + 1;
            counts[ri] = nv;
            touched.push_back(ri);
            if (nv > rows[ri].cap) return false;
        }
        return true;
    }

    void undo(const std::vector<uint32_t>& touched) {
        for (uint32_t ri: touched) counts[ri]--;
    }

    void dfs(int min_q, int depth) {
        if (res.timeout) return;
        if ((res.recursive_calls++ & 0x3FFFULL) == 0 && timed_out()) { res.timeout = true; return; }
        if (depth > res.max_depth) res.max_depth = depth;
        if (depth == target_depth) {
            res.solutions++;
            if ((int)res.solutions_head.size() < max_solutions_store) res.solutions_head.push_back(chosen);
            return;
        }
        int remaining = target_depth - depth;
        for (int q=min_q; q<=255; q++) {
            if (256 - q < remaining) break;
            if (!allowed(q)) continue;
            std::vector<uint32_t> touched;
            bool ok = add_point(q, touched);
            if (ok) {
                res.node_count[depth+1]++;
                chosen.push_back(q);
                dfs(q+1, depth+1);
                chosen.pop_back();
            }
            undo(touched);
            if (res.timeout) return;
        }
    }

    BranchResult run_branch(const BranchSpec& br) {
        res = BranchResult();
        res.branch = br.id; res.rep = br.rep; res.node_count.fill(0); res.node_count[0] = 1;
        std::fill(counts.begin(), counts.end(), 0);
        chosen.clear();
        allowed_words[0]=allowed_words[1]=allowed_words[2]=allowed_words[3]=~0ULL;
        allowed_words[0] &= ~1ULL;
        for (int w=0; w<4; w++) allowed_words[w] &= ~br.forbid[w];
        start = std::chrono::steady_clock::now();

        // Force the branch representative as the first selected point.
        std::vector<uint32_t> touched;
        bool ok = allowed(br.rep) && add_point(br.rep, touched);
        if (ok) {
            res.node_count[1] = 1;
            chosen.push_back(br.rep);
            dfs(br.rep + 1, 1);
            chosen.pop_back();
        }
        undo(touched);
        res.elapsed_sec = std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
        res.complete = !res.timeout;
        return res;
    }

    BranchResult run_prefix(const std::vector<int>& prefix, int branch_id=-2) {
        res = BranchResult();
        res.branch = branch_id; res.rep = prefix.empty()?0:prefix[0]; res.node_count.fill(0); res.node_count[0] = 1;
        std::fill(counts.begin(), counts.end(), 0);
        chosen.clear();
        allowed_words[0]=allowed_words[1]=allowed_words[2]=allowed_words[3]=~0ULL;
        allowed_words[0] &= ~1ULL;
        start = std::chrono::steady_clock::now();
        bool ok = true;
        std::vector<std::vector<uint32_t>> touched_all;
        int last = 0;
        for (int i=0;i<(int)prefix.size();i++) {
            int q = prefix[i];
            if (q <= last || q < 1 || q > 255) { ok=false; break; }
            std::vector<uint32_t> touched;
            if (!add_point(q, touched)) ok=false;
            touched_all.push_back(std::move(touched));
            if (!ok) break;
            chosen.push_back(q);
            res.node_count[i+1] = 1;
            last = q;
        }
        if (ok) dfs(last+1, (int)prefix.size());
        for (auto it=touched_all.rbegin(); it!=touched_all.rend(); ++it) undo(*it);
        res.elapsed_sec = std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
        res.complete = !res.timeout;
        return res;
    }
};

static std::string branch_json(const BranchResult& r) {
    std::ostringstream oss;
    oss << "{\"branch\":" << r.branch << ",\"rep\":" << r.rep
        << ",\"elapsed_sec\":" << std::fixed << std::setprecision(6) << r.elapsed_sec
        << ",\"timeout\":" << (r.timeout?"true":"false")
        << ",\"complete\":" << (r.complete?"true":"false")
        << ",\"recursive_calls\":" << r.recursive_calls
        << ",\"max_depth\":" << r.max_depth
        << ",\"solutions\":" << r.solutions
        << ",\"node_count_by_depth\":" << json_array_u64(r.node_count)
        << ",\"solutions_head\":[";
    for (size_t i=0;i<r.solutions_head.size();i++) {
        if (i) oss << ",";
        oss << json_vec_int(r.solutions_head[i]);
    }
    oss << "]}";
    return oss.str();
}

int main(int argc, char** argv) {
    std::string constraints_path = "data/wang_native/e11_wang_cap5.bin";
    std::string out_path = "data/wang_native/native_dfs_cap5.json";
    int depth = 19;
    double per_branch_time = 60.0;
    int only_branch = -1;
    std::vector<int> prefix;
    for (int i=1;i<argc;i++) {
        std::string a = argv[i];
        if (a == "--constraints" && i+1<argc) constraints_path = argv[++i];
        else if (a == "--out" && i+1<argc) out_path = argv[++i];
        else if (a == "--depth" && i+1<argc) depth = std::stoi(argv[++i]);
        else if (a == "--time-limit" && i+1<argc) per_branch_time = std::stod(argv[++i]);
        else if (a == "--branch" && i+1<argc) only_branch = std::stoi(argv[++i]);
        else if (a == "--prefix" && i+1<argc) {
            std::stringstream ss(argv[++i]); std::string tok;
            while (std::getline(ss, tok, ',')) if (!tok.empty()) prefix.push_back(std::stoi(tok));
        } else {
            std::cerr << "unknown/invalid arg " << a << "\n"; return 2;
        }
    }

    auto t0 = std::chrono::steady_clock::now();
    std::vector<Constraint> rows;
    if (!load_constraints(constraints_path, rows)) return 1;
    auto point_rows = build_point_rows(rows);
    std::cerr << "Loaded " << rows.size() << " constraints from " << constraints_path << "\n";

    Searcher search(rows, point_rows, depth, per_branch_time);
    std::vector<BranchResult> results;
    if (!prefix.empty()) {
        results.push_back(search.run_prefix(prefix));
        std::cout << branch_json(results.back()) << "\n";
    } else {
        auto branches = default_branch_specs();
        for (const auto& b: branches) {
            if (only_branch >= 0 && b.id != only_branch) continue;
            std::cerr << "Branch " << b.id << " rep " << b.rep << "..." << std::endl;
            BranchResult r = search.run_branch(b);
            results.push_back(r);
            std::cout << branch_json(r) << "\n";
            std::cout.flush();
        }
    }
    double elapsed = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    bool all_complete = true; uint64_t total_sol = 0; int global_max_depth = 0;
    std::array<unsigned long long,20> total_nodes{}; total_nodes.fill(0);
    for (const auto& r: results) {
        if (!r.complete) all_complete = false;
        total_sol += r.solutions;
        global_max_depth = std::max(global_max_depth, r.max_depth);
        for (int d=0; d<20; d++) total_nodes[d] += r.node_count[d];
    }

    std::ofstream out(out_path);
    out << "{\n";
    out << "  \"status\": \"ok\",\n";
    out << "  \"constraints_path\": \"" << constraints_path << "\",\n";
    out << "  \"constraint_count\": " << rows.size() << ",\n";
    out << "  \"target_depth\": " << depth << ",\n";
    out << "  \"per_branch_time_limit_sec\": " << per_branch_time << ",\n";
    out << "  \"elapsed_sec\": " << std::fixed << std::setprecision(6) << elapsed << ",\n";
    out << "  \"all_complete\": " << (all_complete?"true":"false") << ",\n";
    out << "  \"total_solutions\": " << total_sol << ",\n";
    out << "  \"global_max_depth\": " << global_max_depth << ",\n";
    out << "  \"total_node_count_by_depth\": [";
    for (int d=0; d<20; d++) { if (d) out << ","; out << total_nodes[d]; }
    out << "],\n";
    out << "  \"branches\": [\n";
    for (size_t i=0;i<results.size();i++) {
        out << "    " << branch_json(results[i]);
        if (i+1<results.size()) out << ",";
        out << "\n";
    }
    out << "  ]\n}\n";
    out.close();
    std::cerr << "Wrote " << out_path << "\n";
    return 0;
}
