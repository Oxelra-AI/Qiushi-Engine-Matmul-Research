// Native deterministic DFS for E11 Wang-admissible 19-point supports.
//
// Input constraints are produced by prepare_e11_wang_constraints.py.  Each row
// has a 256-bit point mask and a cap; a support is valid if every row contains
// at most cap selected points.  The DFS chooses increasing point labels and can
// restrict the first point to a branch representative with all earlier orbits
// forbidden.
//
// This is intended as a transparent exhaustive-search instrument: it reports
// node counts by depth, complete/timeout status, first solutions, and branch
// summaries.  It is not a proof checker by itself; its output becomes evidence
// only together with the decoded row-generation audit and independent replay.

#include <algorithm>
#include <array>
#include <atomic>
#include <chrono>
#include <cstdint>
#include <cstring>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <sstream>
#include <string>
#include <thread>
#include <vector>

struct Constraint {
    uint8_t cap;
    uint8_t dim;
    uint16_t reserved;
    uint64_t word[4];
};

struct BranchSpec {
    int id = -1;
    int rep = 0;
    uint64_t forbid[4] = {0,0,0,0};
};

struct BranchResult {
    int branch = -1;
    int rep = 0;
    double elapsed_sec = 0.0;
    bool timeout = false;
    bool complete = false;
    uint64_t recursive_calls = 0;
    std::array<uint64_t, 20> node_count{};
    int max_depth = 0;
    uint64_t solutions = 0;
    std::vector<std::vector<int>> solutions_head;
};

static int popcount64(uint64_t x) { return __builtin_popcountll(x); }

static bool getbit4(const uint64_t w[4], int p) {
    return (w[p >> 6] >> (p & 63)) & 1ULL;
}

static std::string json_array_u64(const std::array<uint64_t,20>& a) {
    std::ostringstream oss; oss << "[";
    for (int i=0;i<20;i++) { if (i) oss << ","; oss << a[i]; }
    oss << "]"; return oss.str();
}

static std::string json_vec_int(const std::vector<int>& v) {
    std::ostringstream oss; oss << "[";
    for (size_t i=0;i<v.size();i++) { if (i) oss << ","; oss << v[i]; }
    oss << "]"; return oss.str();
}

static bool load_constraints(const std::string& path, std::vector<Constraint>& rows) {
    std::ifstream in(path, std::ios::binary);
    if (!in) { std::cerr << "cannot open " << path << "\n"; return false; }
    char magic[8]; in.read(magic, 8);
    if (!in || std::memcmp(magic, "E11WANG1", 8) != 0) {
        std::cerr << "bad magic in " << path << "\n"; return false;
    }
    uint32_t n = 0; in.read(reinterpret_cast<char*>(&n), sizeof(n));
    rows.resize(n);
    for (uint32_t i=0;i<n;i++) {
        in.read(reinterpret_cast<char*>(&rows[i].cap), 1);
        in.read(reinterpret_cast<char*>(&rows[i].dim), 1);
        in.read(reinterpret_cast<char*>(&rows[i].reserved), 2);
        for (int j=0;j<4;j++) in.read(reinterpret_cast<char*>(&rows[i].word[j]), 8);
    }
    if (!in) { std::cerr << "short read in constraints\n"; return false; }
    return true;
}

static std::vector<std::vector<uint32_t>> build_point_rows(const std::vector<Constraint>& rows) {
    std::vector<std::vector<uint32_t>> pr(256);
    for (uint32_t i=0;i<rows.size();i++) {
        for (int p=1;p<=255;p++) if (getbit4(rows[i].word, p)) pr[p].push_back(i);
    }
    return pr;
}

