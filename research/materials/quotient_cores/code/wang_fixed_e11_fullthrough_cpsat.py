#!/usr/bin/env python3
"""CP-SAT probe for fixed-E11 second-orbit branches with a separate through-prefix.

The earlier range solver uses every fixed point as the prefix for high-dimensional
Wang rows.  For the remaining branches rep2/rep16 we also need the fuller
through-E11 system: after fixing E11 and a second orbit representative, add all
Wang rows of selected high dimensions that contain E11 (or another explicitly
specified through prefix), not only rows that contain the whole fixed pair.

SAT output is only an A-support necessary-condition candidate.  When requested,
the script scans the candidate against the complete Wang LUT by checking every
span generated by subsets of the selected support.  INFEASIBLE remains CP-SAT
execution evidence only until replayed by a proof-producing CNF/DRAT or another
independent certificate.
"""
from __future__ import annotations

