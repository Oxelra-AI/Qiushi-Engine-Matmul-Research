#!/usr/bin/env python3
r"""
analysis: canonical F_2 rank-one-span oracle for the T333 UV-slice space.

Canonical invariant used here
-----------------------------
Let E = F^9 \otimes F^9 be the UV matrix space and let
L = im(T_{333}: W^* -> E) be the nine-dimensional span of the UV slices.
For any field F,

    R(T333) <= r

is equivalent to the existence of r rank-one matrices in E whose linear span
contains L.  Indeed, if T = sum_i x_i \otimes w_i then every UV slice lies in
span{x_i}; conversely, once L is contained in the span of rank-one x_i, the
coordinates of the nine basis slices of L in this span supply the W factors.
By the analysis refinement, the rank <=22 case may be represented with 22
independent UV columns.

Over F_2 the projective rank-one locus has only 511*511 = 261121 points, so a
candidate 22-dimensional subspace S containing L can be checked exactly by
enumeration: S is rank-22-realizing iff the rank-one matrices contained in S
span all of S (dimension 22).  Since S contains L, write S = Q^{-1}(H), where
Q:E -> E/L is a fixed quotient and H is a 13-dimensional subspace of E/L.  Then
rank-one membership is simply Qx in H.

This script builds that oracle and applies it to the most meaningful bounded
families available now:
  * the 14-dimensional quotient H_23 coming from each verified rank-23 seed,
    as a positive control (its rank-one locus should span a 23-dimensional
    space containing L);
  * all 13-dimensional hyperplanes H < H_23.  This tests every 22-dimensional
    subspace containing L inside the UV span of the seed, not merely one-term
    deletions or one arbitrary 13+9 chart;
  * random 13-dimensional H generated by rank-one quotient points, to calibrate
    the generic sparsity of rank-one locus in Q^{-1}(H).

The output is not a global lower bound: it excludes only the tested quotient
families over F_2.  It is, however, an exact, SAT-free finite-field check of the
canonical incidence for those families.
"""
from __future__ import annotations

import argparse
import itertools
import json
import random
import time
from collections import Counter, defaultdict
from pathlib import Path
from typing import Dict, Iterable, List, Tuple

# ----------------------------- bit utilities -----------------------------

def parity(x: int) -> int:
    return x.bit_count() & 1


def gf2_reduce_with_coeff(basis: Dict[int, Tuple[int, int]], v: int) -> Tuple[int, int]:
    """Reduce v by a reduced GF(2) basis.  Return (residual, coeff_mask)."""
    coeff = 0
    while v:
        p = v.bit_length() - 1
        if p not in basis:
            return v, coeff
        bv, bc = basis[p]
        v ^= bv
        coeff ^= bc
    return 0, coeff


def gf2_insert_reduced(basis: Dict[int, Tuple[int, int]], v: int, coeff: int = 0) -> bool:
    """Insert v with coefficient mask coeff into a reduced basis if independent."""
    v, coeff2 = gf2_reduce_with_coeff(basis, v)
    coeff ^= coeff2
    if v == 0:
        return False
    p = v.bit_length() - 1
    # eliminate the new pivot from existing basis vectors to keep reduced form
    for q, (bv, bc) in list(basis.items()):
        if (bv >> p) & 1:
            basis[q] = (bv ^ v, bc ^ coeff)
    basis[p] = (v, coeff)
    return True


def gf2_rank(vecs: Iterable[int]) -> int:
    basis: Dict[int, Tuple[int, int]] = {}
    for v in vecs:
        if v:
            gf2_insert_reduced(basis, int(v), 0)
    return len(basis)


def gf2_basis_with_coords(gens: List[int]) -> Dict[int, Tuple[int, int]]:
    basis: Dict[int, Tuple[int, int]] = {}
    for i, v in enumerate(gens):
        gf2_insert_reduced(basis, int(v), 1 << i)
    return basis


def select_independent_indices(vecs: List[int], target_rank: int | None = None) -> List[int]:
    basis: Dict[int, Tuple[int, int]] = {}
    inds: List[int] = []
    for i, v in enumerate(vecs):
        before = len(basis)
        if gf2_insert_reduced(basis, int(v), 1 << len(inds)):
            inds.append(i)
            if target_rank is not None and len(inds) >= target_rank:
                break
    return inds

# ----------------------- T333 quotient and rank-one set -------------------

def t333_support_by_slice() -> Dict[int, List[int]]:
    by_c = {c: [] for c in range(9)}
    for i in range(3):
        for j in range(3):
            for k in range(3):
                a = 3 * i + j
                b = 3 * j + k
                c = 3 * i + k
                by_c[c].append(a * 9 + b)
    for c in by_c:
        by_c[c] = sorted(by_c[c])
    return by_c


def l_basis_ints() -> List[int]:
    cols = []
    for c, rows in t333_support_by_slice().items():
        x = 0
        for uv in rows:
            x ^= 1 << uv
        cols.append(x)
    assert gf2_rank(cols) == 9
    return cols


def quotient_row_masks() -> List[int]:
    by_c = t333_support_by_slice()
    support = set(itertools.chain.from_iterable(by_c.values()))
    rows: List[int] = []
    # 54 coordinates off the T333 support.
    for uv in range(81):
        if uv not in support:
            rows.append(1 << uv)
    # 18 differences inside the three-point support of each T slice.
    for c in range(9):
        supp = by_c[c]
        anchor = supp[0]
        for uv in supp[1:]:
            rows.append((1 << uv) ^ (1 << anchor))
    assert len(rows) == 72
    return rows


def q_of_x(x: int, qrows: List[int]) -> int:
    q = 0
    for i, mask in enumerate(qrows):
        if parity(x & mask):
            q |= 1 << i
    return q


def outer_rank1_int(u: int, v: int) -> int:
    """Return vec(u v^T) as an 81-bit integer, row-major index 9*a+b."""
    x = 0
    uu = u
    while uu:
        a_bit = uu & -uu
        a = a_bit.bit_length() - 1
        # place v in row a, shifted by 9*a
        x ^= v << (9 * a)
        uu ^= a_bit
    return x


def enumerate_rank_one(qrows: List[int]) -> Tuple[List[int], List[int], Dict[int, List[int]]]:
    xs: List[int] = []
    qs: List[int] = []
    q_to_xs: Dict[int, List[int]] = defaultdict(list)
    for u in range(1, 1 << 9):
        for v in range(1, 1 << 9):
            x = outer_rank1_int(u, v)
            q = q_of_x(x, qrows)
            xs.append(x)
            qs.append(q)
            q_to_xs[q].append(x)
    return xs, qs, q_to_xs

# ----------------------------- qmm loading --------------------------------

def load_qmm_uv_ints(path: Path) -> Tuple[List[int], List[int], List[int]]:
    U: List[List[int]] = []
    V: List[List[int]] = []
    W: List[List[int]] = []
    for line in path.read_text().splitlines():
        parts = line.strip().split()
        if len(parts) >= 10 and parts[0] in ("u", "v", "w"):
            arr = [int(x) & 1 for x in parts[1:10]]
            if parts[0] == "u":
                U.append(arr)
            elif parts[0] == "v":
                V.append(arr)
            else:
                W.append(arr)
    assert len(U) == len(V) == len(W)
    xs = []
    for uarr, varr in zip(U, V):
        u = sum((bit & 1) << i for i, bit in enumerate(uarr))
        v = sum((bit & 1) << i for i, bit in enumerate(varr))
        xs.append(outer_rank1_int(u, v))
    return xs, [sum((bit & 1) << i for i, bit in enumerate(row)) for row in U], [sum((bit & 1) << i for i, bit in enumerate(row)) for row in V]

# ------------------------ canonical subspace oracle ------------------------

def rankone_locus_in_qspan(rank_one_xs: List[int], rank_one_qs: List[int], q_basis_vecs: List[int]) -> Tuple[List[Tuple[int, int]], Dict[str, int]]:
    """Return all rank-one points whose quotient lies in span(q_basis_vecs).

    Each result is (coord_mask in the q-basis, x_int).  q_basis_vecs must be independent.
    """
    solver = gf2_basis_with_coords(q_basis_vecs)
    members: List[Tuple[int, int]] = []
    for x, q in zip(rank_one_xs, rank_one_qs):
        res, coord = gf2_reduce_with_coeff(solver, q)
        if res == 0:
            members.append((coord, x))
    qrank = gf2_rank([coord for coord, _ in members])  # rank in basis coordinates
    xrank = gf2_rank([x for _, x in members])
    return members, {"rankone_count": len(members), "rankone_qrank": qrank, "rankone_xspan_rank": xrank, "l_intersection_dim": xrank - qrank}


def hyperplane_scan(members14: List[Tuple[int, int]], out_examples: int = 5) -> Dict:
    """Scan all 13D hyperplanes of a 14D qspace represented by 14-bit coords."""
    hist = Counter()
    best_records = []
    success = []
    # Pre-store for speed.
    coords = [c for c, _ in members14]
    xs = [x for _, x in members14]
    for f in range(1, 1 << 14):
        inc_coords = []
        inc_xs = []
        for c, x in zip(coords, xs):
            if parity(c & f) == 0:
                inc_coords.append(c)
                inc_xs.append(x)
        qrank = gf2_rank(inc_coords)
        xrank = gf2_rank(inc_xs)
        ldim = xrank - qrank
        cnt = len(inc_xs)
        hist[(qrank, xrank, ldim, cnt)] += 1
        rec = {"functional_mask": f, "rankone_count": cnt, "qrank": qrank, "xspan_rank": xrank, "l_intersection_dim": ldim}
        if qrank == 13 and xrank == 22 and ldim == 9:
            success.append(rec)
            if len(success) >= out_examples:
                # keep scanning for count, but no need to store more examples
                pass
        # keep best by (xrank, ldim, count)
        key = (xrank, ldim, qrank, cnt)
        if len(best_records) < out_examples:
            best_records.append((key, rec))
            best_records.sort(reverse=True, key=lambda z: z[0])
        elif key > best_records[-1][0]:
            best_records[-1] = (key, rec)
            best_records.sort(reverse=True, key=lambda z: z[0])
    # Compress histogram into readable top-level records.
    hist_records = [
        {"qrank": k[0], "xspan_rank": k[1], "l_intersection_dim": k[2], "rankone_count": k[3], "num_hyperplanes": v}
        for k, v in sorted(hist.items(), key=lambda kv: (kv[0][1], kv[0][2], kv[0][0], kv[0][3]))
    ]
    return {
        "num_hyperplanes": (1 << 14) - 1,
        "num_success_rank22": len(success),
        "success_examples": success[:out_examples],
        "best_hyperplanes": [rec for _, rec in best_records],
        "histogram": hist_records,
    }


def random_H13_trials(rank_one_xs: List[int], rank_one_qs: List[int], q_to_xs: Dict[int, List[int]], n_trials: int, seed: int) -> Dict:
    rng = random.Random(seed)
    n = len(rank_one_qs)
    hist = Counter()
    best = []
    successes = []
    # Pre-list nonzero q images; q=0 would mean rank-one element in L, expected none.
    q_nonzero_indices = [i for i, q in enumerate(rank_one_qs) if q != 0]
    for t in range(n_trials):
        # Build a random independent 13D H generated by rank-one quotient points.
        basis_vecs: List[int] = []
        basis = {}
        tries = 0
        while len(basis_vecs) < 13 and tries < 10000:
            idx = rng.choice(q_nonzero_indices)
            q = rank_one_qs[idx]
            if gf2_insert_reduced(basis, q, 1 << len(basis_vecs)):
                basis_vecs.append(q)
            tries += 1
        if len(basis_vecs) < 13:
            continue
        # enumerate all q in H by Gray-style doubling and collect rank-one lifts
        h_values = [0]
        for q in basis_vecs:
            h_values += [v ^ q for v in h_values]
        members_x: List[int] = []
        member_qs: List[int] = []
        for q in h_values:
            xs = q_to_xs.get(q)
            if xs:
                members_x.extend(xs)
                member_qs.extend([q] * len(xs))
        qrank = gf2_rank(member_qs)
        xrank = gf2_rank(members_x)
        ldim = xrank - qrank
        cnt = len(members_x)
        hist[(qrank, xrank, ldim, cnt)] += 1
        rec = {"trial": t, "rankone_count": cnt, "qrank": qrank, "xspan_rank": xrank, "l_intersection_dim": ldim}
        if qrank == 13 and xrank == 22 and ldim == 9:
            successes.append(rec)
        key = (xrank, ldim, qrank, cnt)
        if len(best) < 10:
            best.append((key, rec)); best.sort(reverse=True, key=lambda z: z[0])
        elif key > best[-1][0]:
            best[-1] = (key, rec); best.sort(reverse=True, key=lambda z: z[0])
    hist_records = [
        {"qrank": k[0], "xspan_rank": k[1], "l_intersection_dim": k[2], "rankone_count": k[3], "num_trials": v}
        for k, v in sorted(hist.items(), key=lambda kv: (kv[0][1], kv[0][2], kv[0][0], kv[0][3]))
    ]
    return {"trials_requested": n_trials, "trials_done": sum(hist.values()), "num_success_rank22": len(successes), "success_examples": successes[:5], "best_trials": [rec for _, rec in best], "histogram": hist_records}

# ----------------------------- main analysis ------------------------------

def analyze_seed(name: str, qmm_path: Path, rank_one_xs: List[int], rank_one_qs: List[int], qrows: List[int]) -> Dict:
    xs_terms, _, _ = load_qmm_uv_ints(qmm_path)
    q_terms = [q_of_x(x, qrows) for x in xs_terms]
    x_rank_terms = gf2_rank(xs_terms)
    q_rank_terms = gf2_rank(q_terms)
    indep = select_independent_indices(q_terms, target_rank=q_rank_terms)
    q_basis = [q_terms[i] for i in indep]
    seed_rec = {
        "name": name,
        "qmm_path": str(qmm_path),
        "num_terms": len(xs_terms),
        "term_x_rank": x_rank_terms,
        "term_q_rank": q_rank_terms,
        "term_l_intersection_dim": x_rank_terms - q_rank_terms,
        "independent_q_term_indices": indep,
    }
    if q_rank_terms != 14:
        # Still record the rank-one locus in the actual quotient span, but hyperplane scan is for dim 14.
        members, info = rankone_locus_in_qspan(rank_one_xs, rank_one_qs, q_basis)
        seed_rec["rankone_locus_in_term_qspan"] = info
        seed_rec["hyperplane_scan"] = {"status": "skipped_qrank_not_14"}
        return seed_rec
    members14, info14 = rankone_locus_in_qspan(rank_one_xs, rank_one_qs, q_basis)
    seed_rec["rankone_locus_in_term_qspan"] = info14
    seed_rec["rank23_positive_control_passes"] = (info14["rankone_qrank"] == 14 and info14["rankone_xspan_rank"] >= 23 and info14["l_intersection_dim"] >= 9)
    seed_rec["hyperplane_scan"] = hyperplane_scan(members14)
    return seed_rec


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--random-trials", type=int, default=300)
    ap.add_argument("--seed", type=int, default=20260905029)
    ap.add_argument("--out", default="")
    args = ap.parse_args()

    t0 = time.time()
    ws = Path(__file__).resolve().parent.parent
    outdir = ws / "data/f2_span_oracle"
    outdir.mkdir(parents=True, exist_ok=True)

    qrows = quotient_row_masks()
    L = l_basis_ints()
    assert gf2_rank(qrows) == 72
    assert all(q_of_x(l, qrows) == 0 for l in L)
    print(f"L rank = {gf2_rank(L)}, quotient rows = {len(qrows)}")
    print("Enumerating all F2 rank-one 9x9 matrices...")
    rank_one_xs, rank_one_qs, q_to_xs = enumerate_rank_one(qrows)
    collision_hist = Counter(len(v) for v in q_to_xs.values())
    print(f"  rank-one points: {len(rank_one_xs)}; distinct quotient images: {len(q_to_xs)}; collision_hist={dict(collision_hist)}")
    assert gf2_rank(rank_one_qs) == 72
    assert len(q_to_xs.get(0, [])) == 0
    print(f"  rank of all quotient images: {gf2_rank(rank_one_qs)}; rank-one elements in L (q=0): {len(q_to_xs.get(0, []))}")

    seeds = [
        ("cn122", ws / "data/cn122_r23_reproduce/scheme.qmm"),
        ("serendipitous_8d34", ws / "data/fmm_r23_schemes/serendipitous_8d34.qmm"),
        ("naive_c88", ws / "data/fmm_r23_schemes/naive_c88.qmm"),
    ]
    seed_results = []
    for name, path in seeds:
        if not path.exists():
            print(f"Skipping {name}: missing {path}")
            continue
        print(f"\n=== Seed {name} ===")
        rec = analyze_seed(name, path, rank_one_xs, rank_one_qs, qrows)
        seed_results.append(rec)
        info = rec.get("rankone_locus_in_term_qspan", {})
        print(f"  term ranks: X={rec['term_x_rank']} Q={rec['term_q_rank']} L-intersection={rec['term_l_intersection_dim']}")
        print(f"  rank-one locus in H23: count={info.get('rankone_count')} qrank={info.get('rankone_qrank')} xspan={info.get('rankone_xspan_rank')} Ldim={info.get('l_intersection_dim')}")
        hs = rec.get("hyperplane_scan", {})
        if hs.get("status"):
            print(f"  hyperplanes: {hs['status']}")
        else:
            print(f"  hyperplanes: success={hs['num_success_rank22']} / {hs['num_hyperplanes']}")
            print(f"  best: {hs['best_hyperplanes'][:3]}")

    print(f"\n=== Random 13D quotient subspaces generated by rank-one points ({args.random_trials}) ===")
    rand_rec = random_H13_trials(rank_one_xs, rank_one_qs, q_to_xs, args.random_trials, args.seed)
    print(f"  successes={rand_rec['num_success_rank22']} / {rand_rec['trials_done']}")
    print(f"  best={rand_rec['best_trials'][:5]}")

    result = {
        "purpose": "Exact F2 oracle for the canonical rank-one-span formulation of R(T333)<=22.",
        "field": "F2",
        "canonical_statement": "R(T333)<=r iff the nine-dimensional UV-slice space L is contained in the span of r rank-one 9x9 matrices; for r=22, equivalently there is a 13D quotient subspace H<E/L such that rank-one matrices with Qx in H span Q^{-1}(H).",
        "warning": "Seed-hyperplane exclusions and random trials are not a global lower bound; they test exact bounded families of H.",
        "L_rank": gf2_rank(L),
        "quotient_rows": len(qrows),
        "rank_one_total": len(rank_one_xs),
        "distinct_quotient_images": len(q_to_xs),
        "quotient_collision_hist": {str(k): v for k, v in sorted(collision_hist.items())},
        "rank_all_rank_one_quotient_images": gf2_rank(rank_one_qs),
        "rank_one_in_L_count": len(q_to_xs.get(0, [])),
        "seed_results": seed_results,
        "random_H13": rand_rec,
        "elapsed_sec": round(time.time() - t0, 3),
    }
    out = Path(args.out) if args.out else outdir / "f2_span_oracle_results.json"
    out.write_text(json.dumps(result, indent=2) + "\n")
    print(f"\nSaved {out} in {result['elapsed_sec']}s")


if __name__ == "__main__":
    main()
