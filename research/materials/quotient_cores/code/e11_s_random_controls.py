#!/usr/bin/env python3
"""Random S controls for the E11 S-level quotient-lift obstruction.

For a fixed V, generate random dim-d matrix subspaces S containing the quotient
slice space S_min and test whether R+V tensor S contains a rank<=s tensor.  This
does not produce a quotient algorithm unless S is also generated by quotient
rank-one factors, but it distinguishes an obstruction depending only on V/dim
from one special to the rank-one-generated S spaces found by flip-cpd.
"""
from __future__ import annotations
import argparse, json, random, sys, time
from collections import Counter
from pathlib import Path
import numpy as np

SCRIPTS=Path('scripts')
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0,str(SCRIPTS))
import e11_s_coset_rank_sat as sc  # noqa: E402


def matrix_mask_from_np(M):
    out=0
    for b in range(9):
        row=0
        for c in range(9):
            if int(M[b,c])&1:
                row |= 1<<c
        out |= row << (9*b)
    return out


def random_vec81(rng):
    return rng.getrandbits(81)


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--prefix', required=True)
    ap.add_argument('--dim-S', type=int, default=11)
    ap.add_argument('--rank-res', type=int, default=8)
    ap.add_argument('--samples', type=int, default=50)
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--workdir', type=Path, required=True)
    ap.add_argument('--timeout-per-cover', type=int, default=5)
    ap.add_argument('--threads', type=int, default=4)
    ap.add_argument('--solver', default='cryptominisat5')
    ap.add_argument('--max-covers', type=int, default=5000,
                    help='0 means do not run SAT; only record profiles')
    ap.add_argument('--require-cover-count', type=int, default=-1,
                    help='if >=0, skip random S until this exact cover count appears')
    args=ap.parse_args()
    t0=time.time(); rng=random.Random(args.seed)
    prefix=[int(x) for x in args.prefix.split(',') if x.strip()]
    Q,ann,phis,Rcoords=sc.quotient_base_residual(prefix)
    base=[matrix_mask_from_np(Q[i]) for i in range(Q.shape[0])]
    Smin=sc.rref_basis(base)
    if len(Smin)>args.dim_S:
        raise ValueError('Smin dimension exceeds requested dim')
    args.workdir.mkdir(parents=True, exist_ok=True)
    records=[]; counts=Counter(); profiles=Counter(); cover_counts=Counter()
    seen=set(); attempts=0; skipped_cover_count=Counter()
    while len(records)<args.samples and attempts<max(args.samples*500, 500):
        attempts+=1
        vecs=list(Smin)
        while len(sc.rref_basis(vecs))<args.dim_S:
            vecs.append(random_vec81(rng))
        S=sc.rref_basis(vecs)
        if S in seen:
            continue
        seen.add(S)
        m=sc.m_profile_for_S(Rcoords,S)
        mt=tuple(m[p] for p in range(1,16))
        covers=sc.enumerate_covers(mt,args.rank_res)
        if args.require_cover_count >= 0 and len(covers) != args.require_cover_count:
            skipped_cover_count[len(covers)] += 1
            continue
        profiles[mt]+=1; cover_counts[len(covers)]+=1
        rec={'sample_index':len(records),'attempt_index':attempts,'S_hash':sc.basis_hash(S),'S_dim':len(S),'m_by_phi':{str(k):int(v) for k,v in m.items()},'sum_m_phi':int(sum(m.values())),'valid_cover_count':len(covers),'status':None,'cover_status_counts':{}}
        if not covers:
            rec['status']='NO_VALID_COVER'; counts[rec['status']]+=1; records.append(rec); print(f"sample {rec['sample_index']} no cover sum_m={rec['sum_m_phi']}", flush=True); continue
        if args.max_covers == 0:
            rec['status']='PROFILE_ONLY'; counts[rec['status']]+=1; records.append(rec); print(f"sample {rec['sample_index']} profile covers {len(covers)} sum_m={rec['sum_m_phi']}", flush=True); continue
        if len(covers)>args.max_covers:
            rec['status']='TOO_MANY_COVERS'; counts[rec['status']]+=1; records.append(rec); print(f"sample {rec['sample_index']} too many covers {len(covers)} sum_m={rec['sum_m_phi']}", flush=True); continue
        local=Counter()
        for ci,cover in enumerate(covers):
            enc=sc.FixedASSubspaceSAT(Rcoords,S,cover)
            cnf=args.workdir/f'rand{rec["sample_index"]:03d}_cover{ci:04d}.xor.cnf'
            enc.F.write_native(cnf,[f'random S control sample={rec["sample_index"]}',f'cover={cover}'])
            sol=sc.solve_native(cnf,args.solver,args.timeout_per_cover,args.threads)
            local[sol['status']]+=1
            if cnf.exists() and sol['status']!='SAT':
                cnf.unlink()
            if sol['status']=='SAT':
                rec['sat_cover']=cover; rec['sat_solve']=sol; break
        rec['cover_status_counts']=dict(local)
        if local.get('SAT'):
            rec['status']='SAT_S_INTERSECTION_FOUND'
        elif local.get('UNKNOWN') or local.get('TIMEOUT'):
            rec['status']='UNRESOLVED_COVERS'
        else:
            rec['status']='ALL_COVERS_UNSAT'
        counts[rec['status']]+=1; records.append(rec)
        print(f"sample {rec['sample_index']} sum_m={rec['sum_m_phi']} covers={len(covers)} status={rec['status']} counts={dict(local)}", flush=True)
    result={'purpose':'random S controls containing quotient slice space for E11 S-level lift','field':'F2','prefix':prefix,'annihilator_basis':ann,'phi_vectors':phis,'dim_S':args.dim_S,'rank_res':args.rank_res,'samples_requested':args.samples,'samples_recorded':len(records),'attempts':attempts,'seed':args.seed,'Smin_dim':len(Smin),'Smin_hash':sc.basis_hash(Smin),'status_counts':dict(counts),'m_profile_type_count':len(profiles),'m_profile_counts_head':[{'m_tuple':list(k),'count':int(v)} for k,v in profiles.most_common(20)],'valid_cover_count_distribution':{str(k):int(v) for k,v in sorted(cover_counts.items())},'skipped_cover_count_distribution':{str(k):int(v) for k,v in sorted(skipped_cover_count.items())},'records':records,'elapsed_sec':time.time()-t0}
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(result,indent=2,sort_keys=True,default=int)+'\n')
    print(json.dumps({k:result[k] for k in ['samples_recorded','status_counts','m_profile_type_count','valid_cover_count_distribution','skipped_cover_count_distribution','elapsed_sec']},indent=2,sort_keys=True))
    print('wrote',args.out)

if __name__=='__main__': main()
